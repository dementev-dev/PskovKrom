def to_world(p, u, v):
    return pp.to_world(p.origin, p.yaw, u, v)


def footprint(p):
    """Контур героя в мировых метрах: контур плана, раздвинутый на 0,3 м. У Г-образного дома № 10 центр контура OSM
    лежит во дворе (в 1,6 м от стены) — внутренний угол в футпринте срезан (notch), иначе city_mesh не снимет коробку."""
    ring = list(p.outline)
    notch = getattr(p, "notch", None)
    if notch:
        k, d = notch
        c, a, b = ring[k], ring[k - 1], ring[(k + 1) % len(ring)]
        leg = [(c[0] + d * (q[0] - c[0]) / math.dist(q, c), c[1] + d * (q[1] - c[1]) / math.dist(q, c)) for q in (a, b)]
        ring = ring[:k] + leg + ring[k + 1:]
    return tuple(to_world(p, u, v) for u, v in pp.offset(ring, PLINTH_PROUD))


