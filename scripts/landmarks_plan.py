"""landmarks_plan.py — памятные знаки у Крома: где стоят, куда смотрят, от чего мерить высоту (M5+).

Чистый Python без `unreal` и `bpy`: общий план для scripts/blender/landmarks.py (модели) и scripts/landmarks_krom.py
(расстановка в L_Krom). Координаты — метры проекта: x — север, y — восток, от центра Троицкого собора.

    python scripts/landmarks_plan.py     # точки, азимуты, самопроверка

Модель знака строится в своих осях: u — «лицо» знака (туда он смотрит, к зрителю), v — вправо от u (yaw + 90°),
z — от точки отсчёта высоты. В уровне актор ставится в xy с yaw = азимут u (от севера к востоку, как у башен).
Высота: земля (трасса по Landscape) в ground_at (пусто — в xy) плюс dz. У «Меча Довмонта» отсчёт — верх лица Персей
(уровень двора Крома у стены + низ кровли над внешней гранью): композиция висит на стене, а не стоит на земле.

Источники — REFERENCES S-86…S-89, памятник Ленину — S-135…S-137, памятник княгине Ольге и амфитеатр Детского
парка — S-153…S-155; всё, что снято с фото «на глаз», — гипотеза (в note).
"""
import math
from dataclasses import dataclass

import krom_plan as plan


@dataclass(frozen=True)
class Landmark:
    name: str            # подпись актора в Outliner
    asset: str           # SM_Mark_<Имя>: build/blender/<asset>.glb → /Game/Krom/Environment/Landmarks/<asset>
    xy: tuple            # точка установки
    yaw: float           # азимут оси u модели, °
    ground_at: tuple = ()   # где мерить землю (пусто — в xy)
    dz: float = 0.0      # от земли в ground_at до нуля модели
    osm: str = ""
    note: str = ""

    @property
    def height_at(self):
        return self.ground_at or self.xy


# ---------- «Меч Довмонта» на Персях ----------
PERSI = "Перси: Довмонтова — Троицкая"
SWORD_S = 57.6   # путь от Довмонтовой по внешней грани: сюда проецируется узел OSM 4808553360 (0,7 м от линии)


def wall_face(run_name, s):
    """Точка на внешней грани участка стены (линия OSM) в s метрах от начала и азимут нормали наружу (от двора)."""
    r = next(r for r in plan.wall_runs() if r.name == run_name)
    acc = 0.0
    for a, b in zip(r.points, r.points[1:]):
        L = math.dist(a, b)
        if L > 1e-9 and acc + L >= s:
            k = (s - acc) / L
            t = ((b[0] - a[0]) / L, (b[1] - a[1]) / L)
            left = (-t[1], t[0])                              # WallRun.yard: +1 — двор слева (−dy, dx)
            out = left if r.yard == -1 else (-left[0], -left[1])
            p = (a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k)
            return p, math.degrees(math.atan2(out[1], out[0])) % 360, r
        acc += L
    raise ValueError(f"{run_name}: s = {s} за концом участка ({acc:.1f} м)")


