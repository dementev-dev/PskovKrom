    road = plan.WallRun("улица", "конец", "конец", tuple(plan.osm_way(ROAD_NEAR_OLGA)), plan.WALLS[654691936][1], -1)
    d_road = plan.station(road, OLGA_CROSS.xy)[0]
    assert d_road > 2.5 + 0.72 + 0.3, d_road
    # буквы: нижняя набережная ровная по всей длине надписи (±24 м вдоль азимута 352°)
    t = (math.cos(math.radians(LETTERS.yaw + 90)), math.sin(math.radians(LETTERS.yaw + 90)))
    zs = hm.at([(LETTERS.xy[0] + s * t[0], LETTERS.xy[1] + s * t[1]) for s in range(-24, 25, 2)])
    assert zs.max() - zs.min() < 0.3, zs.max() - zs.min()
    print(f"Ольгин крест: до оси улицы {d_road:.1f} м; буквы: земля по длине {zs.min():+.2f}…{zs.max():+.2f} м")
    # памятник Ленину: площадка (u −5…7,25, v ±6,75) — на мощении площади, земля под ней не круче полуметра перепада
    import osm_layers
    tl = math.radians(LENIN.yaw)
    U, V = (math.cos(tl), math.sin(tl)), (-math.sin(tl), math.cos(tl))
    corners = [(LENIN.xy[0] + a * U[0] + b * V[0], LENIN.xy[1] + a * U[1] + b * V[1]) for a in (-5.0, 7.25)
               for b in (-6.75, 6.75)]
    zs = hm.at([(LENIN.xy[0] + a * U[0] + b * V[0], LENIN.xy[1] + a * U[1] + b * V[1])
                for a in [-5.0 + 0.5 * i for i in range(25)] for b in [-6.75 + 0.5 * j for j in range(28)]])
    z_foot = float(hm.at([LENIN.height_at])[0])
    assert all(osm_layers.in_squares(q) for q in corners + [LENIN.height_at]), "площадка не на мощении площади"
    assert zs.max() - z_foot < LENIN_BURY_CHECK and z_foot - zs.min() < 0.25, (zs.min(), z_foot, zs.max())
    import pskovgu_plan
    mp = pskovgu_plan.MainPlan()
    ty = math.radians(mp.yaw)
    off = (LENIN.xy[0] - mp.origin[0]) * math.cos(ty) + (LENIN.xy[1] - mp.origin[1]) * math.sin(ty)
    print(f"Ленин: земля под площадкой {zs.min() - z_foot:+.2f}…{zs.max() - z_foot:+.2f} м от нижней ступени; "
          f"от оси портика ПсковГУ вдоль фасада {off:+.1f} м (OSM; на фото — 0)")
    # памятник Ольге: лицом к собору (±5°), лестница — на мощение площадки, под площадкой (r 5,5 + лестница) земля
    # не выше нижней ступени + OLGA_BURY_CHECK и не ниже на 0,25
    az0 = math.degrees(math.atan2(-OLGA.xy[1], -OLGA.xy[0])) % 360
    assert abs(OLGA.yaw - az0) < 5, (OLGA.yaw, az0)
    assert osm_layers.in_squares(OLGA.height_at, ids=(OLGA_PLAZA,)), "лестница не на мощении площадки"
    ring = [(OLGA.xy[0] + r * math.cos(math.radians(a)), OLGA.xy[1] + r * math.sin(math.radians(a)))
            for r in (0.0, 2.0, 4.0, 5.5) for a in range(0, 360, 15)]
    zs = hm.at(ring)
    z_foot = float(hm.at([OLGA.height_at])[0])
    assert zs.max() - z_foot < OLGA_BURY_CHECK and z_foot - zs.min() < 0.25, (zs.min(), z_foot, zs.max())
    print(f"Ольга: азимут на собор {az0:.1f}°, земля под площадкой {zs.min() - z_foot:+.2f}…{zs.max() - z_foot:+.2f} м "
          f"от нижней ступени; узел OSM 803818497 — в {math.dist(OLGA.xy, (-646.7, 355.1)):.1f} м")
    # амфитеатр: центр дуг и радиусы рядов — по скамейкам OSM (средний радиус каждой скамьи от центра), оси блоков
    rad = []
