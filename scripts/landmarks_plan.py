def amph_stage_uv():
    """Контур мощёной площадки перед рядами в осях амфитеатра (u — к среднему проходу, v — вправо): [(u, v)]."""
    t = math.radians(AMPH_YAW)
    out = []
    for x, y in plan.geo.open_ring(plan.osm_way(AMPH_STAGE_WAY)):
        dx, dy = x - AMPH_CENTER[0], y - AMPH_CENTER[1]
        out.append((round(dx * math.cos(t) + dy * math.sin(t), 2), round(-dx * math.sin(t) + dy * math.cos(t), 2)))
    return out


