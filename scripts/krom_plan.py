def _make_run(wall, profile, yard, pts, a, b, obstacles):
    pts = simplify(pts, 0.3)

    def snap(end, o):
        if o is not None:
            return o.name, None
        near = min(obstacles, key=lambda t: dist_to_poly(end, t.footprint))
        if dist_to_poly(end, near.footprint) <= SNAP_M:
            return near.name, near.origin
        return "конец", None

    (an, ap), (bn, bp) = snap(pts[0], a), snap(pts[-1], b)
    pts = ([ap] if ap else []) + pts + ([bp] if bp else [])
    return WallRun(wall, an, bn, tuple(pts), profile, yard)


def _yard_normal(run, i):
    """Единичная нормаль к двору у отрезка i трассы — как в wall_mesh.Path."""
    (ax, ay), (bx, by) = run.points[i], run.points[i + 1]
    L = math.hypot(bx - ax, by - ay)
    return -(by - ay) / L * run.yard, (bx - ax) / L * run.yard


def _at(run, s):
    """Точка трассы на пути s от начала участка и номер её отрезка."""
    s0, last = 0.0, len(run.points) - 2
    for i, (a, b) in enumerate(zip(run.points, run.points[1:])):
        L = math.dist(a, b)
        if L > 1e-9 and (s <= s0 + L or i == last):
            k = (s - s0) / L
            return (a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k), i
        s0 += L
    raise ValueError(run.name)


def _shifted(runs, w):
    """Отрезки трасс, каждый сдвинут к двору на w (без «уса» в вершинах)."""
    out = []
    for r in runs:
        for i, (a, b) in enumerate(zip(r.points, r.points[1:])):
            if math.dist(a, b) > 1e-9:
                m = _yard_normal(r, i)
                out.append(((a[0] + m[0] * w, a[1] + m[1] * w), (b[0] + m[0] * w, b[1] + m[1] * w)))
    return out


def _ray_hit(p, d, segs):
    """Ближайшее пересечение луча p + λ·d (λ > 0) с отрезками: λ или None."""
    best = None
    for (ax, ay), (bx, by) in segs:
        ex, ey = bx - ax, by - ay
        den = d[0] * ey - d[1] * ex
        if abs(den) < 1e-12:
            continue
        qx, qy = ax - p[0], ay - p[1]
        lam, mu = (qx * ey - qy * ex) / den, (qx * d[1] - qy * d[0]) / den
        if lam > 1e-6 and -1e-6 <= mu <= 1 + 1e-6 and (best is None or lam < best):
            best = lam
    return best


def _join(r, j, runs, gates):
    """Участок r, у которого конец j.end дотянут в тело стены j.to (WallJoin)."""
    pts = list(r.points)
    i = 0 if j.end == 0 else len(pts) - 2          # отрезок у этого конца
    p, q = (pts[0], pts[1]) if j.end == 0 else (pts[-1], pts[-2])
    L = math.dist(p, q)
    d = ((p[0] - q[0]) / L, (p[1] - q[1]) / L)       # наружу от участка
    m = _yard_normal(r, i)
    nbrs = [n for n in runs if n.wall == j.to]
    if j.gate:
        # откос проёма, от которого тело стыка уходит в сторону от проезда: точка на грани двора соседа и точка
        # на JOIN_IN_M глубже, по нормали его отрезка
        name, s, g = next((name, s, g) for name, gs in gates.items() for s, g in gs if g.name == j.gate)
        n = next(n for n in runs if n.name == name)
        for e in (-1, 1):
            o, k = _at(n, s + e * g.width / 2)
            mn = _yard_normal(n, k)
            tn = (mn[1] * n.yard, -mn[0] * n.yard)                   # вдоль трассы соседа
            run_dir = mn if j.end == 0 else (-mn[0], -mn[1])        # ход участка по откосу: внутрь → к двору
            own = (-run_dir[1] * r.yard, run_dir[0] * r.yard)       # куда от него тело стыка
            if e * (own[0] * tn[0] + own[1] * tn[1]) > 0:            # проезд — по другую сторону откоса
                break
        else:
            raise ValueError(f"{r.name}: нет откоса «{j.gate}», от которого тело уходит в сторону")
        face = (o[0] + mn[0] * n.profile.t, o[1] + mn[1] * n.profile.t)
        inner = (o[0] + mn[0] * (n.profile.t - JOIN_IN_M), o[1] + mn[1] * (n.profile.t - JOIN_IN_M))
        new = [inner, face]
        reach = math.dist(face, p)
    else:
        outer = _shifted(nbrs, 0.0)
        deep = [seg for n in nbrs for seg in _shifted([n], n.profile.t - JOIN_IN_M)]
        edges = (p, (p[0] + m[0] * r.profile.t, p[1] + m[1] * r.profile.t))   # оба края тела у конца
        hits = [_ray_hit(e, d, deep) for e in edges]
        if None in hits:
            raise ValueError(f"{r.name}: луч от конца не встречает стену «{j.to}»")
        reach = max(hits)
        for e in edges:   # и не проходит соседа насквозь
            out = _ray_hit(e, d, outer)
            if out is not None and out < reach:
                raise ValueError(f"{r.name}: стык проходит стену «{j.to}» насквозь")
        new = [(p[0] + d[0] * reach, p[1] + d[1] * reach)]
    if reach > JOIN_MAX_M:
        raise ValueError(f"{r.name}: до стены «{j.to}» {reach:.1f} м — больше JOIN_MAX_M")
    pts = new + pts if j.end == 0 else pts + new[::-1]
    return WallRun(r.wall, r.a, r.b, tuple(pts), r.profile, r.yard)


