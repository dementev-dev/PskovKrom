def hero_round_tower(t):
    """Building круглой башни по RoundTowerPlan: примитивы blockout из тех же чисел, контур — средний диаметр."""
    dm = (t.d[0] + t.d[1]) / 2
    parts = (Part("cyl", (0, 0), (dm, dm), (0, t.z_eave), "stone"),
             Part("cone", (0, 0), (2 * t.eave_r, 2 * t.eave_r), (t.z_eave, t.z_tent + t.tent_r * 2), "wood"))
    if t.lookout:
        lr, l0, l1 = t.lookout
        parts += (Part("cyl", (0, 0), (2 * lr, 2 * lr), (l0, l1), "wood"),
                  Part("cone", (0, 0), (2 * t.lookout_eave[0],) * 2, (t.lookout_eave[1], t.z_top), "wood"))
    return Building(t.name, "Towers", t.center, 0.0, parts, circle(t.center, dm / 2), t.note, hero=t.hero,
                    base=t.base)


@dataclass(frozen=True)
class FacetTowerPlan:
    """Гранёная башня — четверик или восьмерик из плитняка с тёсовым шатром: общий план для blockout и героя
    scripts/blender/facet_tower.py. Оси башни: u — по азимуту yaw, v — вправо (yaw + 90°), z — метры от земли
    в точке base (там, откуда сняты отметки). Контур у земли — прямоугольник size (по u, по v) со срезанными углами
    chamfer (facet_contour: 0 — четверик; у правильного восьмерика — 0,293 ширины). К верху стены сходятся на taper
    с каждой стороны. Шатёр — пирамида над контуром свеса (верх стен + eave) от z_eave: излом kick = (отступ от края
    свеса внутрь, z), дальше скаты до вершины z_tent, либо до вышки — тогда шатёр усечён на полуширине tent_r, а вышка
    такая же, как у RoundTowerPlan (lookout_kind, lookout, lookout_eave). Грани считаются по азимуту своей нормали
    в осях башни: 0 — перед (+u), 90 — правая (+v), у восьмерика ещё 45, 135 …
    Кровля шатра — tent_mat: тёс (wood) с подзором и стыком тёса, иначе листовая (медь, сталь) — гладкие скаты
    с рёбрами по углам."""
    name: str
    center: tuple
    yaw: float
    size: tuple          # (по u, по v) у земли
    chamfer: float       # срез углов (по каждой оси)
    z_eave: float        # верх стен — нижний край свеса шатра
    eave: float          # вынос свеса за стены
    kick: tuple          # (отступ от края свеса, z) — низ скатов шатра после излома («полицы»)
    z_tent: float        # вершина шатра (или верх усечённого шатра под вышкой)
    z_top: float         # вершина шатра или шатрика вышки — там яблоко
    z_vane: float        # верх флюгера
    base: tuple          # точка нуля высот (x, y)
    taper: float = 0.0   # сужение стен к верху с каждой стороны
    tent_r: float = 0.0  # полуширина верха усечённого шатра под вышкой (0 — шатёр до вершины)
    lookout_kind: str = ""
    lookout: tuple = ()
    lookout_eave: tuple = ()
    belts: tuple = ()    # пояса: ((z низа, высота, вынос), ...)
    slits: tuple = ()    # бойницы и окна: ((z низа, высота, ширина, ((азимут грани, смещение от середины), ...)), ...)
    holes: tuple = ()    # круглые бойницы: ((z середины, диаметр, ((азимут грани, смещение от середины), ...)), ...)
    gate: tuple = ()     # проезд насквозь вдоль оси u: (ширина, пята свода от земли, смещение по v); пусто — нет
    doors: tuple = ()    # арочные двери в нише: ((азимут грани, смещение, ширина, пята свода), ...), створка — тёс
    kiot: tuple = ()     # киот над воротами: (азимут грани, низ, ширина, высота) — килевидная рамка с образом
    lookout_sides: int = 0  # 4 — вышка-четверик с шатриком (Власьевская); 0 — круглая, как у RoundTowerPlan
    mat: str = "stone"   # стены: stone — открытый плитняк, wall — белёные (Рыбницкая)
    tent_mat: str = "wood"  # кровля шатра: wood — тёс; copper — медь (Довмонтова)
    vane: str = ""       # флюгер: "" — флажок (bl_krom.finial); warrior — прапор с фигурой воина (Довмонтова)
    z_foot: float = -3.0  # низ тела от base
    hero: str = ""
    note: str = ""

    @property
    def sides(self):
        return 8 if self.chamfer > 0 else 4


def facet_contour(size, chamfer, grow=0.0):
    """Контур гранёной башни в осях (u, v): прямоугольник size со срезанными на chamfer углами, раздутый наружу на grow
    (свес, пояс; grow < 0 — внутрь). Первая грань — передняя (+u), дальше по возрастанию азимута нормали."""
    hu, hv = size[0] / 2 + grow, size[1] / 2 + grow
    if chamfer <= 0:
        return [(hu, -hv), (hu, hv), (-hu, hv), (-hu, -hv)]
    c = chamfer + grow * (2 - math.sqrt(2))   # срез 45° при сдвиге грани наружу на grow
    return [(hu, -hv + c), (hu, hv - c), (hu - c, hv), (-hu + c, hv),
            (-hu, hv - c), (-hu, -hv + c), (-hu + c, -hv), (hu - c, -hv)]


