def chapel(c):
    """Часовня (blockout): массы по ChapelPlan. Детальная модель — scripts/blender/chapels.py (hero)."""
    s, (dd, z_drum), (od, z_dome, z_tip) = c.side, c.drum, c.dome
    if c.arm:   # крестовый: угловые части до z_eave, рукава до пяты закомар, над ними — пирамида до верха закомар
        parts = (Part("box", (0, 0), (s, s), (0, c.z_eave), "wall"),
                 Part("box", (0, 0), (s, c.arm), (0, c.z_gable - c.arm / 2), "wall"),
                 Part("box", (0, 0), (c.arm, s), (0, c.z_gable - c.arm / 2), "wall"),
                 Part("pyr", (0, 0), (s + 0.2, s + 0.2), (c.z_eave, c.z_gable), "dark"))
        roof = "dark"
    else:       # четверик под кровлей по щипцам — пирамидой
        parts = (Part("box", (0, 0), (s, s), (0, c.z_eave), "wall"),
                 Part("pyr", (0, 0), (s + 0.6, s + 0.6), (c.z_eave - 0.1, c.z_gable + 0.9), "green"))
        roof = "green"
    parts += (Part("cyl", (0, 0), (dd, dd), (c.z_eave, z_drum), "wall"),
              Part("sphere", (0, 0), (od, od), (z_dome, z_dome + 0.8 * (z_tip - z_dome)), roof),
              Part("cone", (0, 0), (0.5 * od, 0.5 * od), (z_dome + 0.5 * (z_tip - z_dome), z_tip), roof),
              Part("box", (0, 0), (0.08, 0.08), (z_tip, c.z_top), "gold"))
    fp = tuple(geo.open_ring(osm_way(c.way)))
    return Building(c.name, "Zavelichye", c.center, c.yaw, parts, fp, c.note, hero=c.hero)


def min_area_rect(poly):
    """Прямоугольник минимальной площади вокруг многоугольника: (центр, азимут оси, длина, ширина)."""
    best = None
    for p, q in zip(poly, poly[1:] + poly[:1]):
        yaw = math.degrees(math.atan2(q[1] - p[1], q[0] - p[0]))
        t = math.radians(yaw)
        us = [x * math.cos(t) + y * math.sin(t) for x, y in poly]
        vs = [-x * math.sin(t) + y * math.cos(t) for x, y in poly]
        area = (max(us) - min(us)) * (max(vs) - min(vs))
        if best is None or area < best[0]:
            u0, v0 = (max(us) + min(us)) / 2, (max(vs) + min(vs)) / 2
            best = (area, to_world((0, 0), yaw, u0, v0), yaw % 360, max(us) - min(us), max(vs) - min(vs))
    return best[1:]


