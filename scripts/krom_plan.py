@dataclass(frozen=True)
class Part:
    """Примитив в осях здания: u — по азимуту yaw, v — вправо от него (yaw + 90°), z — метры над базой."""
    shape: str   # box | cyl | cone | sphere | pyr (4 грани) | oct (8 граней) | pyr8; размер граней — по граням
    uv: tuple    # центр в плане
    size: tuple  # размер по u и по v
    z: tuple     # (низ, верх) над базой; низ ≤ 0 — «от земли»: опускается до рельефа под зданием
    mat: str     # ключ цвета, см. COLORS


@dataclass(frozen=True)
class Building:
    name: str
    group: str       # папка в Outliner
    origin: tuple    # (x, y); база по высоте — земля в этой точке
    yaw: float       # азимут оси u, градусы от севера к востоку (= yaw в UE)
    parts: tuple
    footprint: tuple  # контур в плане (x, y) — режет стены и сажает здание на рельеф
    note: str = ""
    hero: str = ""   # StaticMesh героя M3 (scripts/blender → heroes_krom.py); есть ассет — примитивов parts нет
    base: tuple = ()  # (x, y): земля в этой точке — нуль высот здания; пусто — земля в origin

    @property
    def ground_at(self):
        return self.base or self.origin


@dataclass(frozen=True)
class WallProfile:
    """Поперечник стены (D-021), метры. w — от внешней грани (линия OSM) к двору, z — от земли двора.
    Тело из плитняка толщиной t до боевого хода. По внешней грани — бруствер толщиной parapet с бойницами, он доходит
    до кровли. Ход шириной walk за бруствером, по его внутреннему краю — столбы. Над ходом — односкатная тёсовая
    кровля: конёк над внешней гранью на h, скат во двор с уклоном pitch; под ней у столбов — head в рост.
    Отсюда уровень хода (фото kutekroma_yard: ход ≈4,8, свес у столбов ≈7,3, конёк ≈8,6 м от земли у калитки).
    roof=False — простая стена с плоским верхом на h."""
    t: float                  # толщина тела
    h: float                  # верх со двора: конёк кровли (S-23: с кровлей 7,4–9,4 м) или кладка, если roof=False
    walk: float = 1.5         # ширина боевого хода
    parapet: float = 0.9      # толщина бруствера (гип.)
    head: float = 2.1         # от настила до кровли у столбов (фото, гип.)
    pitch: float = 25.0       # уклон кровли, ° (фото kutekroma_yard: над ходом ≈1,3 м подъёма)
    roof_t: float = 0.12      # толщина тёса
    eave: tuple = (0.3, 0.5)  # свес кровли наружу за грань и во двор за столбы
    post_step: float = 2.7    # шаг столбов (фото kutekroma_yard, гип.)
    slit: tuple = (5.4, 0.35, 0.9, 1.5)   # бойницы: шаг, ширина, низ и верх над ходом (гип.)
    roof: bool = True

    def roof_under(self, w):
        """Низ кровли над точкой w поперёк стены, от земли двора."""
        return self.h - math.tan(math.radians(self.pitch)) * w - self.roof_t / math.cos(math.radians(self.pitch))

    @property
    def z_walk(self):
        """Настил боевого хода (для простой стены — её верх)."""
        return self.roof_under(self.parapet + self.walk) - self.head if self.roof else self.h


@dataclass(frozen=True)
class WallRun:
    """Участок стены между башнями (или до конца линии OSM). Линия points — внешняя грань, двор — со стороны yard:
    +1 — слева по ходу линии в осях плана (−dy, dx), −1 — справа."""
    wall: str
    a: str           # что в начале: башня / «конец»
    b: str
    points: tuple    # ломаная (x, y)
    profile: WallProfile
    yard: int
    level_at: tuple = ()  # (x, y): уровень двора — земля в этой точке для всего участка; пусто — земля у двора

    @property
    def name(self):
        return f"{self.wall}: {self.a} — {self.b}"

    @property
    def length(self):
        return sum(math.dist(p, q) for p, q in zip(self.points, self.points[1:]))

    @property
    def thickness(self):
        return self.profile.t

    @property
    def height(self):
        """Высота со двора с кровлей — для коробок blockout."""
        return self.profile.h


