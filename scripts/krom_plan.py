# Для blockout (pskov_church, pskov_belfry) он — пристройка: коробка до z_eave и пирамида до z_high.

@dataclass(frozen=True)
class TierOctagon(TierAnnex):
    """Восьмерик: ярус TierAnnex, в плане — прямоугольник u0…u1 × v0…v1 со срезанными под 45° углами (катет chamfer;
    0 — a / (2 + √2) от меньшей стороны a: у квадрата — правильный восьмерик), стенки толщиной wall от z0 до верха
    карниза z_eave (вынос карниза cornice), низкая восьмискатная кровля mat_roof до z_high, её верх — восьмерик
    размером r_top от оси (под барабан главы). opening — сквозной арочный проём в каждой грани (ширина, низ, пята)
    с решёткой и отливом, пол — на 0,1 ниже низа проёма; arcs — рельефные арки по граням (z пят в углах, z верха),
    () — без них; bell — ⌀ колокола на балке (0 — без него). Поля ChurchAnnex windows, doors, arches, brows, piers
    и roof генератор у восьмерика не читает."""
    chamfer: float = 0.0
    wall: float = 0.8
    opening: tuple = ()
    cornice: float = 0.35
    r_top: float = 0.5
    arcs: tuple = ()
    bell: float = 0.0


