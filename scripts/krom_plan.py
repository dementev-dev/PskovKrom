def dovmont_foundations():
    """Раскрытые фундаменты храмов Довмонтова города — контуры OSM (building=ruins: ways и мультиполигоны),
    коробками по описанному прямоугольнику. Высота над землёй 0,8 м — гип. (на деле они в раскопе ниже площади)."""
    els = osm_elements()
    ways = {e["id"]: e for e in els if e["type"] == "way"}
    out = []
    for e in els:
        t = e.get("tags", {})
        if t.get("building") != "ruins" or e["id"] in SKIP_FOUNDATIONS:
            continue
        if e["type"] == "way" and None not in e["geometry"]:
            ring = geo.open_ring(geo.local_points(e["geometry"]))
        elif e["type"] == "relation":   # мультиполигон (r4060623 — самый большой, 629 м²): внешнее кольцо
            rings = geo.assemble_rings([(ways[m["ref"]]["nodes"], geo.local_points(ways[m["ref"]]["geometry"]))
                                        for m in e["members"] if m["role"] == "outer" and m["ref"] in ways])
            if not rings:
                continue
            ring = list(max(rings, key=lambda r: abs(geo.signed_area(r))))
        else:
            continue
        (cx, cy), yaw, du, dv = min_area_rect(ring)
        if not (-260 < cx < -60 and -40 < cy < 110):  # только Довмонтов город и Захаб
            continue
        parts = (Part("box", (0, 0), (du, dv), (0, 0.8), "ruin"),)
        name = f"Фундамент {e['id']}" if e["type"] == "way" else f"Фундамент r{e['id']}"
        out.append(Building(name, "Dovmont", (cx, cy), yaw, parts,
                            rect((cx, cy), yaw, du, dv), f"OSM {e['type']} {e['id']}"))
    return out


