def pskov_church(p):
    """Храм псковской школы (blockout): массы по PskovChurchPlan. Детальная модель — scripts/blender/pskov_church.py."""
    u0, u1, v0, v1 = p.quad
    (qu, ql), (qv, qw) = span(u0, u1), span(v0, v1)
    parts = [Part("box", (qu, qv), (ql, qw), (0, p.z_quad), "wall"),
             Part("pyr", (qu, qv), (ql + 1, qw + 1), (p.z_quad, p.z_gable), p.roof_mat)]
    for a in p.annexes:
        (au, al), (av, aw) = span(a.u0, a.u1), span(a.v0, a.v1)
        parts += [Part("box", (au, av), (al, aw), (0, a.z_eave), "wall"),
                  Part("pyr", (au, av), (al + 0.6, aw + 0.6), (a.z_eave, a.z_high), a.mat_roof)]
    for a in p.apses:
        (au, al), (av, aw) = span(u1, a.tip), span(a.v0, a.v1)
        parts.append(Part("box" if a.kind == "rect" else "cyl", (au, av), (al, aw), (0, a.z), "wall"))
    for d in p.domes:
        parts += [Part("cyl", (d.u, d.v), (d.drum_d, d.drum_d), (p.z_quad, d.z_lip), "wall")]
        parts += onion(d.u, d.v, d.onion_d, d.z_lip, d.z_apple, d.z_top - d.z_apple, d.mat)
    fp = tuple(to_world(p.center, p.yaw, u, v) for u, v in p.outline())
    return Building(p.name, p.group, p.center, p.yaw, tuple(parts), fp, p.note, hero=p.hero)


def pskov_belfry(p):
    """Отдельная звонница (blockout): массы по PskovBelfryPlan. Детальная модель — scripts/blender/pskov_church.py."""
    parts = []
    for a in p.blocks:
        (au, al), (av, aw) = span(a.u0, a.u1), span(a.v0, a.v1)
        parts += [Part("box", (au, av), (al, aw), (0, a.z_eave), "wall"),
                  Part("pyr", (au, av), (al + 0.6, aw + 0.6), (a.z_eave, a.z_high), a.mat_roof)]
    z = p.zvon
    (zu, zl), (zv, zw) = span(z.u0, z.u1), span(z.v0, z.v1)
    parts += [Part("box", (zu, zv), (zl, zw), (0, z.z_eave), "wall"),
              Part("pyr", (zu, zv), (zl + 1.2, zw + 1.2), (z.z_eave, z.z_ridge), z.mat_roof)]
    fp = tuple(geo.open_ring(osm_way(p.way))) if p.way else \
        rect(p.center, p.yaw, p.size[0], p.size[1])
    return Building(p.name, p.group, p.center, p.yaw, tuple(parts), fp, p.note, hero=p.hero, base=p.base)


