    def body(r):
        """Тело участка в плане — по четырёхугольнику на отрезок трассы (0..t к двору)."""
        out = []
        for i, (a, b) in enumerate(zip(r.points, r.points[1:])):
            if math.dist(a, b) > 1e-9:
                m = _yard_normal(r, i)
                t = r.profile.t
                out.append((a, b, (b[0] + m[0] * t, b[1] + m[1] * t), (a[0] + m[0] * t, a[1] + m[1] * t)))
