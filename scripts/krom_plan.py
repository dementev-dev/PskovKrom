def to_world(origin, yaw, u, v):
    t = math.radians(yaw)
    return origin[0] + u * math.cos(t) - v * math.sin(t), origin[1] + u * math.sin(t) + v * math.cos(t)


def circle(center, r, n=24):
    return tuple((center[0] + r * math.cos(2 * math.pi * i / n), center[1] + r * math.sin(2 * math.pi * i / n))
                 for i in range(n))


def rect(origin, yaw, du, dv, u0=0.0, v0=0.0):
    return tuple(to_world(origin, yaw, u0 + su * du / 2, v0 + sv * dv / 2)
                 for su, sv in ((-1, -1), (1, -1), (1, 1), (-1, 1)))


# ---------- башни ----------

def round_tower(name, center, d, h, tent, note):
    """Круглая башня: цилиндр до основания шатра + конический шатёр с небольшим свесом."""
    parts = (Part("cyl", (0, 0), (d, d), (0, h - tent), "wall"),
             Part("cone", (0, 0), (d * 1.08, d * 1.08), (h - tent, h), "wood"))
    return Building(name, "Towers", center, 0.0, parts, circle(center, d / 2), note)


def oct_tower(name, center, yaw, d, h, tent, note):
    """Восьмигранная башня: призма (d — по граням) + восьмискатный шатёр."""
    parts = (Part("oct", (0, 0), (d, d), (0, h - tent), "wall"),
             Part("pyr8", (0, 0), (d * 1.08, d * 1.08), (h - tent, h), "wood"))
    r = d / 2 / math.cos(math.pi / 8)
    return Building(name, "Towers", center, yaw, parts, circle(center, r, 8), note)


def rect_tower(name, center, yaw, du, dv, h, tent, note):
    """Прямоугольная башня: короб до основания шатра + четырёхскатный шатёр."""
    parts = (Part("box", (0, 0), (du, dv), (0, h - tent), "wall"),
             Part("pyr", (0, 0), (du * 1.06, dv * 1.06), (h - tent, h), "wood"))
    return Building(name, "Towers", center, yaw, parts, rect(center, yaw, du, dv), note)


@dataclass(frozen=True)
class RoundTowerPlan:
    """Круглая башня с тёсовым шатром — общий план для blockout и героя scripts/blender/round_tower.py.
    z — метры от земли в точке base: там, откуда сняты отметки (у Кутекромы — двор Крома, у Плоской — берег у воды).
    Радиусы — от оси. Шатёр: у края свеса (eave_r, z_eave) — излом («полица»), дальше конус от kick до (tent_r, z_tent).
    Вышка (lookout_kind): "open" — открытая на столбах с перилами (Кутекрома), "closed" — глухая, обшитая тёсом,
    с окошками (Высокая), "" — вышки нет: конус сходится в точку z_tent (tent_r = 0), lookout и lookout_eave пусты,
    z_top = z_tent — там яблоко и шпиль с флюгером."""
    name: str
    center: tuple
    d: tuple             # тело: диаметр внизу и у свеса; средний — контур для стен (footprint)
    z_eave: float        # нижний край свеса шатра
    eave_r: float
    kick: tuple          # (r, z) — низ конуса шатра после излома
    z_tent: float        # верх конуса
    tent_r: float
    lookout: tuple       # вышка: (r столбов или стенок, низ, верх); низ — верх пояска над шатром
    lookout_eave: tuple  # зонтик вышки: (r края, z края, z у шатрика)
    z_top: float         # вершина шатрика вышки (без вышки — вершина шатра)
    z_vane: float        # верх флюгера
    slits: tuple         # ярусы бойниц: ((z низа, высота, ширина, (азимуты от севера к востоку, °)), ...)
    base: tuple          # точка нуля высот (x, y)
    hero: str = ""
    note: str = ""
    lookout_kind: str = "open"
    z_foot: float = -3.0  # низ тела от base: снаружи земля ниже (по heightmap_L_Krom под контуром)
    plinth: tuple = ()    # (вынос, верх) — откос-подошва у земли: тело расширяется книзу на вынос; пусто — нет


