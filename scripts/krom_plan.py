def hero_facet_tower(t):
    """Building гранёной башни по FacetTowerPlan: примитивы blockout из тех же чисел, контур — стены у земли."""
    su, sv = t.size
    body, roof = ("oct", "pyr8") if t.sides == 8 else ("box", "pyr")
    z1 = t.z_tent + t.tent_r * 2 if t.lookout else t.z_tent
    parts = (Part(body, (0, 0), (su, sv), (0, t.z_eave), "stone"),
             Part(roof, (0, 0), (su + 2 * t.eave, sv + 2 * t.eave), (t.z_eave, z1), t.tent_mat))
    if t.lookout:
        lr, l0, l1 = t.lookout
        parts += (Part("cyl", (0, 0), (2 * lr, 2 * lr), (l0, l1), "wood"),
                  Part("cone", (0, 0), (2 * t.lookout_eave[0],) * 2, (t.lookout_eave[1], t.z_top), "wood"))
    fp = tuple(to_world(t.center, t.yaw, u, v) for u, v in facet_contour(t.size, t.chamfer))
    return Building(t.name, "Towers", t.center, t.yaw, parts, fp, t.note, hero=t.hero, base=t.base)


@functools.lru_cache(maxsize=1)
def osm_elements():
    return geo.load_elements(geo.latest("krom_2*.json"))


def osm_way(way_id):
    w = next(e for e in osm_elements() if e["type"] == "way" and e["id"] == way_id)
    return [p for p in geo.local_points(w["geometry"]) if p]


