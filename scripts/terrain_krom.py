def osm_shapes():
    """Слои OSM в пределах Landscape (с запасом): кольца воды и линии стен — для rasterio (x = Y, y = X)."""
    m = HALF + 50
    polys, lines = osm_layers.collect((-m, m, -m, m))
    walls = [line for line, _ in lines["Wall"]]
    swap = lambda pts: [(y, x) for x, y in pts]  # noqa: E731
    water_geoms = [{"type": "Polygon", "coordinates": [swap(r) + swap(r[:1])]} for r in polys["Water"] if len(r) > 2]
    wall_geoms = [{"type": "LineString", "coordinates": swap(w)} for w in walls]
    return water_geoms, wall_geoms, walls, polys, lines


