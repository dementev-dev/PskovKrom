def plateau(dem, weight):
    """Поверхность суши от «надёжных» пикселей DEM, продолженная к воде: нормализованная свёртка,
    от грубого масштаба к тонкому, чтобы не оставалось дыр вдали от надёжных точек."""
    out = None
    for sigma in (80.0, 30.0, 12.0):
        num = ndimage.gaussian_filter(dem * weight, sigma)
        den = ndimage.gaussian_filter(weight, sigma)
        val = num / np.maximum(den, 1e-9)
        a = np.clip(den / 0.2, 0.0, 1.0)
        out = val if out is None else a * val + (1 - a) * out
    return out


def _mask(ring, blur=1.0):
    """Кольцо (x, y) → доля «внутри» на сетке Landscape (строки — север вверху), края смягчены на blur м."""
    geom = [{"type": "Polygon", "coordinates": [[(y, x) for x, y in ring] + [(ring[0][1], ring[0][0])]]}]
    m = features.rasterize(geom, out_shape=(N, N), transform=MAP_T, fill=0, default_value=1).astype(np.float64)
    return ndimage.gaussian_filter(m, blur) if blur else m


def _dist_to_line(px, py, line):
    """Расстояние от точек (px, py) до ломаной line, м."""
    d = np.full(px.shape, np.inf)
    for (ax, ay), (bx, by) in zip(line, line[1:]):
        ex, ey = bx - ax, by - ay
        t = np.clip(((px - ax) * ex + (py - ay) * ey) / max(ex * ex + ey * ey, 1e-12), 0.0, 1.0)  # точки-дубли
        d = np.minimum(d, np.hypot(px - ax - t * ex, py - ay - t * ey))
    return d


def _nearest_on_line(px, py, line):
    """Расстояние от точек (px, py) до ломаной line и положение ближайшей точки на ней — метры от начала ломаной."""
    d, s, s0 = np.full(px.shape, np.inf), np.zeros(px.shape), 0.0
    for (ax, ay), (bx, by) in zip(line, line[1:]):
        ex, ey = bx - ax, by - ay
        L = np.hypot(ex, ey)
        t = np.clip(((px - ax) * ex + (py - ay) * ey) / (L * L), 0.0, 1.0)
        dd = np.hypot(px - ax - t * ex, py - ay - t * ey)
        s = np.where(dd < d, s0 + t * L, s)
        d = np.minimum(d, dd)
        s0 += L
    return d, s


def zakhab_corridor(into_wall=0.0):
    """Контур захаба (D-026): от наружной грани Великих ворот по стене захаба и назад по восточной стене. into_wall —
    линия стены захаба (её грань к захабу) сдвинута на столько метров в тело, к двору."""
    runs = krom_plan.wall_runs()
    run = next(r for r in runs if r.wall == "Захаб")
    zakhab = [tuple(p) for p in run.points]
    if into_wall:
        P = np.array(zakhab)
        seg = np.diff(P, axis=0)
        seg /= np.hypot(*seg.T)[:, None]
        yard = run.yard * np.c_[-seg[:, 1], seg[:, 0]]  # WallRun.yard: +1 — (−dy, dx), −1 — (dy, −dx)
        nv = np.r_[yard[:1], yard[:-1] + yard[1:], yard[-1:]]
        nv /= np.hypot(*nv.T)[:, None]
        zakhab = [tuple(p) for p in P + nv * into_wall]
    trinity = [tuple(p) for p in next(r for r in runs if r.name.startswith("Восточная: Троицкая")).points]
    return [GATE_OUT] + zakhab + [p for p in reversed(trinity) if p[0] <= run.points[-1][0] + 8.0]


def persi_step(h):
    """Перепад у Персей (D-026) в абсолютных высотах h; возвращает новые h и отметки для отчёта."""
    runs = krom_plan.wall_runs()
    persi = [tuple(p) for p in next(r for r in runs if r.wall == "Перси").points]  # линия — наружная грань
    west = [tuple(p) for p in next(r for r in runs if r.name.startswith("Западная: Довмонтова")).points]
    east = [[tuple(p) for p in r.points] for r in runs
            if r.name.startswith("Восточная: Рыбницкая") or r.wall == "Довмонтов город, восточная"]
    corridor = zakhab_corridor()

    x = (HALF - np.arange(N, dtype=np.float64))[:, None] * np.ones((1, N))
    y = (np.arange(N, dtype=np.float64) - HALF)[None, :] * np.ones((N, 1))
    d = _dist_to_line(x, y, persi)
    # сторона Персей — по самой линии стены (с контрфорсами), а не по контурам OSM: те идут иначе, и полоса у подошвы
    # попадала то в «Кром» (поднималась до двора), то никуда — вдоль стены оставались горбы
    south = _mask(persi + [(persi[-1][0] - 300.0, persi[-1][1]), (persi[0][0] - 300.0, persi[0][1] + 60.0)], blur=0.7)  # запад — вдоль стены
    south = np.maximum(south, 1 - smoothstep((d - PERSI_STEP_IN_M) / 0.7))  # и полтела стены
    dov = np.maximum(_mask(osm_layers.relation_ring(DOVMONT_REL)), south * (1 - smoothstep((d - 20.0) / 10.0)))
    krom = _mask(osm_layers.relation_ring(KROM_REL)) * (1 - south)
    cor = _mask(corridor)
    band = (krom > 0.99) & (cor < 0.01) & (d >= YARD_BAND_M[0]) & (d <= YARD_BAND_M[1])
    yard = float(h[band].mean())

    # двор за Персями — до земли двора (насыпной, у стены DEM проседает)
    lift = krom * (1 - cor) * (1 - smoothstep((d - YARD_LIFT_M[0]) / (YARD_LIFT_M[1] - YARD_LIFT_M[0])))
    h = h + lift * np.maximum(0.0, yard - h)

    # к югу: ложбина у стены, газон, у ворот — дорога; к PERSI_FADE_M — прежний рельеф; только ниже, не выше
    a, b = PERSI_DITCH_M
    prof = PERSI_FOOT_M + (PERSI_LAWN_M - PERSI_FOOT_M) * smoothstep((d - a) / (b - a))
    dg = np.hypot(x - GATE_OUT[0], y - GATE_OUT[1])
    prof = prof + (GATE_M - prof) * (1 - smoothstep((dg - 5.0) / (GATE_R_M - 5.0)))
    fade = 1 - smoothstep((d - PERSI_FADE_M[0]) / (PERSI_FADE_M[1] - PERSI_FADE_M[0]))
    low = np.minimum(h, h + fade * (yard + prof - h))
    h = h + dov * (low - h)
    # бровка берега снаружи западной стены Довмонтова города: иначе газон внутри ниже земли снаружи (склон не трогаем)
    bank = (1 - dov) * (1 - krom) * smoothstep((west[0][0] - x) / 10.0) * (1 - smoothstep(_dist_to_line(x, y, west) / WEST_BANK_M))
    h = h + bank * (np.minimum(h, h + fade * (yard + PERSI_LAWN_M - h)) - h)
    # и к востоку от восточной стены: земля поднимается от газона к городу на EAST_BANK_M (южнее Троицкой)
    d_east = np.min([_dist_to_line(x, y, line) for line in east], axis=0)
    bank = (1 - dov) * (1 - krom) * (1 - cor) * smoothstep((GATE_OUT[0] - x) / 15.0) * (1 - smoothstep(d_east / EAST_BANK_M))
    h = h + bank * (np.minimum(h, h + fade * (yard + PERSI_LAWN_M - h)) - h)

    # захаб: от порога ворот вверх до двора; ступень к двору — посередине тела стены захаба (как у Персей: на грани
    # размытие маски поднимало пол у стены на ≈1 м и давало поперечный уклон дорожки до 16 %)
    cor = _mask(zakhab_corridor(ZAKHAB_STEP_IN_M), blur=ZAKHAB_BLUR_M)
    (ax, ay), (bx, by) = ZAKHAB_AXIS
    ex, ey = bx - ax, by - ay
    u = np.clip(((x - ax) * ex + (y - ay) * ey) / (ex * ex + ey * ey), 0.0, 1.0)
    h = h + cor * ((yard + GATE_M) * (1 - u) + h * u - h)
    # пол проезда Великих ворот сквозь Перси и под зданием — ровно на пороге; полоса (GATE_HALF_M) кончается у
    # выхода из проезда, дальше — подъём захаба без уступа
    (gx, gy), (ix, iy) = GATE_OUT, GATE_EXIT
    L = np.hypot(ix - gx, iy - gy)
    ux, uy = (ix - gx) / L, (iy - gy) / L
    gate = [(gx - ux * 2, gy - uy * 2), (ix - ux * GATE_HALF_M, iy - uy * GATE_HALF_M)]
    w = 1 - smoothstep((_dist_to_line(x, y, gate) - GATE_HALF_M) / 1.5)
    h = h + w * (yard + GATE_M - h)
    return h, {"yard": yard}


def holy_gate(h, h_street):
    """Святые ворота (HOLY_*): проезд — один ровный подъём от уровня улицы снаружи (h_street — рельеф у тротуара до
    persi_step) на HOLY_RISE_M внутрь; у концов — ровные площадки, дальше — к рельефу persi_step. Абсолютные высоты."""
    (ox, oy), (ix, iy) = HOLY_OUT, HOLY_IN
    L = np.hypot(ox - ix, oy - iy)
    ux, uy = (ox - ix) / L, (oy - iy) / L       # изнутри наружу
    r0, r1 = int(HALF - max(ox, ix)) - 50, int(HALF - min(ox, ix)) + 50
    c0, c1 = int(min(oy, iy) + HALF) - 50, int(max(oy, iy) + HALF) + 50
    win = np.s_[r0:r1, c0:c1]
    x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                       indexing="ij")
    a = (x - ix) * ux + (y - iy) * uy            # вдоль проезда от внутреннего конца
    b = np.abs(-(x - ix) * uy + (y - iy) * ux)   # поперёк
    tgt = h_street + HOLY_RISE_M * (1 - np.clip(a / L, 0.0, 1.0))
    inside = a < L / 2
    d = np.hypot(np.maximum(np.maximum(-a, a - L), 0.0), b)  # до отрезка проезда
    apron = np.where(inside, HOLY_APRON_M[0], HOLY_APRON_M[1])
    fade = np.where(inside, HOLY_FADE_M[0], HOLY_FADE_M[1])
    w = 1 - smoothstep((d - apron) / (fade - apron))
    persi = [tuple(p) for p in next(r for r in krom_plan.wall_runs() if r.wall == "Перси").points]
    w = w * np.where(inside, smoothstep((_dist_to_line(x, y, persi) - HOLY_PERSI_M[0])
                                        / (HOLY_PERSI_M[1] - HOLY_PERSI_M[0])), 1.0)
    h = h.copy()
    h[win] += w * (tgt - h[win])
    return h


def pskova_terrace(h, water, d_land, d_wall):
    """Терраса набережной Псковы вдоль тропы TERRACE_WAY и земля под Т-площадкой моста 2024 г. на Запсковье —
    в абсолютных высотах h. Сечение как на фото (env10, env11): тропа без поперечного уклона, у воды — подпорная
    стенка габионов вровень с тропой (ярусы внутри коробов), за лицом — берма ≈1:3 до уреза; к холму — насыпь вровень
    (склон не срезается). У стен (WALL_KEEP_M) и в воде рельеф прежний. Возвращает новые h, сводку для отчёта и полосу
    камня у уреза под бермой (N × N, для маски)."""
    els = {e["id"]: e for e in geo.load_elements(geo.latest("krom_2*.json"))}
    path = geo.local_points(els[TERRACE_WAY]["geometry"])
    path = path[:next((i for i, p in enumerate(path) if p[0] < TERRACE_END_X), len(path))]  # как в gabions_krom
    # продольный профиль через 1 м: у устоя моста 2024 г. — TERRACE_ABS, дальше — TERRACE_BASE_ABS, на Стрелке —
    # спуск к урезу
    P = np.array(path)
    S = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(P, axis=0).T))])
    s = np.arange(0.0, S[-1] + 0.5, 1.0)
    px, py = np.interp(s, S, P[:, 0]), np.interp(s, S, P[:, 1])
    h_s, dl_s = (ndimage.map_coordinates(a, [HALF - px, py + HALF], order=1) for a in (h, d_land))
    (gx, gy), gr, steps = GABION_STEPS
    s_b = s[np.argmin(np.hypot(px - gx, py - gy))]
    flat, ramp = TERRACE_BRIDGE_M
    target = TERRACE_BASE_ABS + (TERRACE_ABS - TERRACE_BASE_ABS) * (1 - smoothstep((np.abs(s - s_b) - flat) / ramp))
    level_s = np.maximum(h_s[0] + (target - h_s[0]) * smoothstep(s / TERRACE_RAMP_M), h_s)  # где склон выше — склон
    n_s = 1 + (steps - 1) * (1 - smoothstep((np.hypot(px - gx, py - gy) - gr) / 10.0))  # ярусов; за радиусом — плавно

    m = 60  # окно вокруг тропы и площадки
    (bx0, by0), (bx1, by1) = BRIDGE_2024
    r0, r1 = int(HALF - max(P[:, 0].max(), bx1)) - m, int(HALF - P[:, 0].min()) + m
    c0, c1 = int(P[:, 1].min() + HALF) - m, int(max(P[:, 1].max(), by1) + HALF) + m
    win = np.s_[r0:r1, c0:c1]
    x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                       indexing="ij")
    hw, dl, rim = h[win], d_land[win], WATER_LEVEL_ABS + SHORE_RIM_M

    d, sp = _nearest_on_line(x, y, path)
    lev, h_p, dl_p, n = (np.interp(sp, s, a) for a in (level_s, h_s, dl_s, n_s))
    # к воде: тропа ровно до габионов; спуск на ярусы — внутри коробов (не на грани: LOD, D-026); у лица — земля на
    # n ярусов ниже тропы; дальше берма 1:3, а если вода ближе — ровный откос до уреза; другой берег не трогаем
    face = GABION_IN_M + n * GABION_DEPTH_M
    foot = lev - n * GABION_DEPTH_M
    boxes = lev - n * GABION_DEPTH_M * np.clip((d - GABION_IN_M - 0.3) / (n * GABION_DEPTH_M - 0.6), 0.0, 1.0)
    need = (foot - rim) / np.maximum(dl_p - face, 0.5)
    # ровный откос — не выше земли у лица: на мыске у смотровой площадки Стрелки (вода обходит тропу, dl > dl_p)
    # он иначе поднимал горб над рекой (D-039, замечание по снимку)
    berm = np.where(need <= BERM_GRADE, np.maximum(foot - (d - face) * BERM_GRADE, rim),
                    np.maximum(np.minimum(rim + need * np.maximum(dl, 0.0), foot - (d - face) * CAPE_GRADE), rim))
    wet = np.where(d <= GABION_IN_M, lev, np.where(d <= face, boxes, berm))
    # другой берег — где отрезок до ближайшей точки тропы пересекает воду — не трогаем
    qx, qy = np.interp(sp, s, px), np.interp(sp, s, py)
    cross = np.zeros(d.shape, bool)
    for t in (0.2, 0.4, 0.6, 0.8):
        rr = np.clip(np.rint(HALF - (x + t * (qx - x))).astype(int), 0, N - 1)
        cc = np.clip(np.rint(y + t * (qy - y) + HALF).astype(int), 0, N - 1)
        cross |= water[rr, cc]
    side = (dl < dl_p) & (d <= dl_p + 1.0) & ~cross
    # за концами тропы (ближайшая точка — конец) сечение не строим: там берег у Советского моста и устье — прежние
    inner = (sp > 0.5) & (sp < S[-1] - 0.5)
    # к холму: полоса тропы и насыпь вровень на TERRACE_FILL_M, дальше откос 1:2; склон холма не срезаем; насыпь
    # не выше чем в 1,5 раза против подъёма тропы (терраса гаснет с ним)
    out = np.maximum(d - TERRACE_HALF_M, 0.0)
    hill = np.clip(lev - TERRACE_FILL_GRADE * np.maximum(out - TERRACE_FILL_M, 0.0) - hw, 0.0,
                   1.5 * np.maximum(lev - h_p, 0.0) + 0.2)
    # мыс у смотровой площадки Стрелки ≈(296, −84): клетки дальше dl_p + 1 от тропы, но ближе к воде, чем к ней, —
    # не «холм»: насыпь вровень поднимала их до тропы горбом над рекой (замечание по снимку after2_strelka)
    spit = (dl < dl_p) & (dl < d) & ~side
    delta = np.where(side, wet - hw, np.where(cross | spit, 0.0, hill))
    delta = np.where(inner, delta, np.maximum(delta, 0.0))  # за концами — только насыпь, как было (D-037)
    # у стен — прежний рельеф (бровка D-014); к холму — только ближе к тропе, чем к стенам
    keep = smoothstep((d_wall[win] - WALL_KEEP_M[0]) / (WALL_KEEP_M[1] - WALL_KEEP_M[0]))
    delta = delta * keep * np.where(side, 1.0, smoothstep((d_wall[win] - d) / 4.0))
    riprap = np.zeros((N, N), bool)
    riprap[win] = side & (d > face) & (dl <= BERM_RIPRAP_M) & ~water[win] & (keep > 0.5)
    up = delta

    # Т-площадка на Запсковье: земля вровень под плитой настила (на 0,1 м ниже верха) и за площадкой на PLATFORM_FILL_M;
    # подъём у воды — на 1 м внутри блока площадки (его лицо к воде остаётся стенкой); по сторонам — насыпь и откос
    L = np.hypot(bx1 - bx0, by1 - by0)
    ux, uy = (bx1 - bx0) / L, (by1 - by0) / L
    a = (x - bx0) * ux + (y - by0) * uy - L
    t = np.abs((y - by0) * ux - (x - bx0) * uy)
    pl, pw = PLATFORM_M
    out = np.hypot(np.maximum(np.maximum(-a, a - pl - PLATFORM_FILL_M), 0.0), np.maximum(t - pw / 2, 0.0))
    top = TERRACE_ABS - 0.1
    plat = np.where((a >= 1.0) & (out == 0), top,
                    np.minimum(top - PLATFORM_FILL_GRADE * out, rim + PLATFORM_BANK * (dl - 1.0)))
    plat_up = np.clip(plat - hw, 0.0, None)
    up = np.where(plat_up > 0, np.maximum(up, plat_up), up) * ~water[win]
    h = h.copy()
    h[win] += up
    return h, {"flat_m": int((level_s >= TERRACE_ABS - 0.01).sum()), "len_m": float(S[-1]), "rise_max": float(up.max()),
               "lower_max": float(-up.min()), "base_m": int((np.abs(level_s - TERRACE_BASE_ABS) < 0.01).sum())}, riprap


def underpass(h):
    """Набережная Великой (UNDERPASS_WAY) под Ольгинским мостом (замечание владельца по снимку: низ балки у самой
    дорожки): полоса дорожки опускается так, чтобы под балкой было UNDERPASS_CLEAR_M; к обе стороны — не круче
    UNDERPASS_GRADE (только срезка). Настил — как в bridge_krom: земля у концов оси OSM + deck_above, толщина и высота
    балки у берега. Абсолютные высоты; возвращает h и отметку дорожки под балкой (от собора)."""
    els = {e["id"]: e for e in geo.load_elements(geo.latest("krom_2*.json")) if e["type"] == "way"}
    path = np.array([p for p in geo.local_points(els[UNDERPASS_WAY]["geometry"]) if p])
    br = [p for p in geo.local_points(els[UNDERPASS_BRIDGE]["geometry"]) if p]
    (ax, ay), (bx, by) = br[0], br[-1]
    z_at = lambda px, py: float(ndimage.map_coordinates(h, [[HALF - px], [py + HALF]], order=1)[0])  # noqa: E731
    za, zb = z_at(ax, ay) + UNDERPASS_DECK_ABOVE, z_at(bx, by) + UNDERPASS_DECK_ABOVE
    # пересечение оси моста с дорожкой
    S = np.r_[0.0, np.cumsum(np.hypot(*np.diff(path, axis=0).T))]
    best = None
    for i in range(len(path) - 1):
        p, q = path[i], path[i + 1]
        d1, d2 = q - p, np.array([bx - ax, by - ay])
        den = d1[0] * d2[1] - d1[1] * d2[0]
        if abs(den) < 1e-9:
            continue
        t = ((ax - p[0]) * d2[1] - (ay - p[1]) * d2[0]) / den
        u = ((ax - p[0]) * d1[1] - (ay - p[1]) * d1[0]) / den
        if 0 <= t <= 1 and 0 <= u <= 1:
            best = (S[i] + t * np.hypot(*d1), u)
    if best is None:
        return h, None
    s_c, u_c = best
    girder = za + (zb - za) * u_c - UNDERPASS_DECK_T - UNDERPASS_GIRDER
    top = girder - UNDERPASS_CLEAR_M
    m = int(UNDERPASS_REACH_M + 20)
    cx, cy = np.interp(s_c, S, path[:, 0]), np.interp(s_c, S, path[:, 1])
    r0, r1, c0, c1 = int(HALF - cx) - m, int(HALF - cx) + m, int(cy + HALF) - m, int(cy + HALF) + m
    win = np.s_[r0:r1, c0:c1]
    x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                       indexing="ij")
    d, sp = _nearest_on_line(x, y, [tuple(p) for p in path])
    tgt = top + UNDERPASS_GRADE * np.abs(sp - s_c)
    w = (1 - smoothstep((d - UNDERPASS_HALF_M) / UNDERPASS_BLEND_M)) * (np.abs(sp - s_c) <= UNDERPASS_REACH_M)
    hw = h[win]
    h = h.copy()
    h[win] = hw + w * np.minimum(tgt - hw, 0.0)
    return h, top - float(h[HALF, HALF])


def finpark(h, water, d_land):
    """Финский парк и плотина (P-1, P-2, P-4 разведки finpark и долина finpark_valley) — в абсолютных высотах h: суша
    у верхнего бьефа не ниже его уровня + POOL_RIM_M, долина парка (дно от уровня бьефа, один крутой склон к
    ул. Воровского), берег у устоев вровень с их верхом, протока. Порядок: P-1 → долина к западу от пешеходного моста
    (finpark_west) → долина парка → P-2 (только подъём) → P-4 (только срезка): так долина не срезает землю у устоя.
    Возвращает новые h и описание воды выше плотины для landscape_krom (уровень в м от собора — снаружи)."""
    import finpark_plan
    pool = WATER_LEVEL_ABS + finpark_plan.HEAD_M
    els = {e["id"]: e for e in geo.load_elements(geo.latest("krom_2*.json")) if e["type"] == "way"}
    line = lambda i: [p for p in geo.local_points(els[i]["geometry"]) if p]  # noqa: E731
    x = (HALF - np.arange(N, dtype=np.float64))[:, None] * np.ones((1, N))
    y = (np.arange(N, dtype=np.float64) - HALF)[None, :] * np.ones((N, 1))
    (ax, ay), (bx, by) = POOL_WEIR
    cx, cy = np.mean(POOL_RING, axis=0)
    side = lambda px, py: np.sign((bx - ax) * (py - ay) - (by - ay) * (px - ax))  # noqa: E731
    up = side(x, y) == side(cx, cy)                               # выше гребня
    pool_w = water & (_mask(list(POOL_RING), blur=0) > 0.5)
    d_pool = ndimage.distance_transform_edt(~pool_w)
    h = h.copy()
    out = {}
    # P-1: суша у верхнего бьефа — не ниже уровня + POOL_RIM_M
    rim = up & ~water & (d_pool <= POOL_RIM_REACH_M)
    raised = np.maximum(pool + POOL_RIM_M - h, 0.0) * rim
    h += raised
    out["pool_rim_cells"] = int((raised > 0.01).sum())
    # долина к западу от пешеходного моста (до Советского моста), затем долина парка: её переход у FP_WEST ложится на
    # новый рельеф запада
    h, out["west"] = finpark_west(h, water, pool_w, up, line)
    h, out["valley"] = finpark_valley(h, water, pool_w, d_pool, pool, line)
    # P-2: устои плотины — вровень с верхом (только подъём)
    for corners, top in DAM_ABUTMENTS:
        inside = _mask(list(corners), blur=0) > 0.5
        d = ndimage.distance_transform_edt(~inside)
        w = np.where(inside, 1.0, (1 - smoothstep((d - DAM_FLAT_M) / DAM_BLEND_M)) * ~water)
        h = h + w * np.maximum(top - h, 0.0)
    # P-4: протока — русло и берега (только срезка)
    ds = _dist_to_line(x, y, list(STREAM_PTS))
    bed = (pool - STREAM_BED_M + (STREAM_BED_M + STREAM_BANK_M)
           * np.clip((ds - STREAM_BED_HALF_M) / (STREAM_EDGE_M - STREAM_BED_HALF_M), 0.0, 1.0)
           + np.maximum(ds - STREAM_EDGE_M, 0.0) * STREAM_SIDE_GRADE)
    w = (1 - smoothstep((ds - STREAM_REACH_M[0]) / (STREAM_REACH_M[1] - STREAM_REACH_M[0]))) * up * ~water
    h = h + w * np.minimum(bed - h, 0.0)
    out["stream_bed"] = pool - STREAM_BED_M
    out["pool_abs"] = pool
    return h, out


def finpark_west(h, water, pool_w, up, line):
    """Долина Псковы от Советского моста до пешеходного моста у плотины (finpark_west) — в абсолютных высотах h, до
    finpark_valley. Южный берег между водой нижнего бьефа и Милицейской улицей (FPW_RIM_WAY): дно — как в долине парка,
    но от уровня WATER_LEVEL_ABS (низкий берег FP_FLOOR_EDGE_M, газон + FP_FLOOR_M, у южного конца пешеходного моста —
    фартук FP_APRON_Z, у воды — не круче FP_LOW_GRADE); склон — один, от речной кромки улицы (высота — h на её оси до
    правила, скользящее среднее FP_RIM_SMOOTH_M) к дну по smoothstep шириной FP_SLOPE_RUN × перепад; склон только
    срезает. Улица и терраса за ней, другой берег, выше гребня и у Советского моста (FPW_KEEP_M) — прежний рельеф. Зона
    заходит за FP_WEST: переход finpark_valley ложится на новый рельеф. Возвращает новые h и сводку."""
    r0, r1 = HALF - 40, HALF + 201                   # окно: X от 40 до −200 м
    c0, c1 = HALF + 140, HALF + 761                  # Y от 140 до 760 м
    win = np.s_[r0:r1, c0:c1]
    x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                       indexing="ij")
    hw, wet = h[win], water[win]
    d_low = ndimage.distance_transform_edt(~(water & ~pool_w))[win]
    street = line(FPW_RIM_WAY)[FPW_RIM_NODES[0]:FPW_RIM_NODES[1] + 1]   # с запада на восток
    # зона: от оси Псковы (между Советским мостом и гребнем) до улицы; у моста замыкается под настилом (FPW_KEEP_M)
    axis = [p for p in line(61729642) if 170.0 < p[1] < 680.0]          # с востока на запад
    ring = street + [line(66837904)[-1], POOL_WEIR[1]] + axis
    zone = (_mask(ring, blur=0)[win] > 0.5) & ~wet & ~up[win]
    # дно
    lvl = WATER_LEVEL_ABS
    top = lvl + FP_FLOOR_M
    floor = np.minimum(lvl + FP_FLOOR_EDGE_M + FP_FLOOR_GRADE * np.maximum(d_low - FP_SHORE_M, 0.0), top)
    d_a = _dist_to_line(x, y, FP_APRON_SEG)
    floor += ((1 - smoothstep((d_a - FP_APRON_M[0]) / (FP_APRON_M[1] - FP_APRON_M[0])))
              * np.maximum(FP_APRON_Z - floor, 0.0))
    shore = lvl + POOL_RIM_M + (FP_FLOOR_EDGE_M - POOL_RIM_M) * smoothstep(d_low / FP_SHORE_M)
    floor = np.where(d_low < FP_SHORE_M, np.minimum(floor, shore), floor)
    floor = np.minimum(floor, lvl + POOL_RIM_M + FP_LOW_GRADE * d_low)
    # склон: бровка — речная кромка улицы, высота — ось улицы до правила (через 1 м, скользящее среднее)
    d_b, s_b = _nearest_on_line(x, y, street)
    P = np.array(street)
    L = np.r_[0.0, np.cumsum(np.hypot(*np.diff(P, axis=0).T))]
    sl = np.arange(0.0, L[-1], 1.0)
    rim_line = ndimage.map_coordinates(h, [HALF - np.interp(sl, L, P[:, 0]), np.interp(sl, L, P[:, 1]) + HALF], order=1)
    rim = np.interp(s_b, sl, ndimage.uniform_filter1d(rim_line, int(FP_RIM_SMOOTH_M), mode="nearest"))
    k0, k1 = FPW_RIM_M
    W = np.clip(FP_SLOPE_RUN * (rim - top), *FP_SLOPE_W_M)
    W = np.minimum(W, np.maximum(d_b + d_low - k0 - FP_TOE_WATER_M, 4.0))   # подошва не ближе FP_TOE_WATER_M к воде
    slope = floor + np.maximum(rim - floor, 0.0) * smoothstep(1 - (d_b - k0) / W)
    tgt = np.minimum(slope, np.maximum(hw, floor))   # склон только срезает (у улицы — без бортика), дно — по отметке
    # вес: зона с мягким краем (1,5 м), у улицы — к прежнему рельефу, у Советского моста — прежний рельеф
    d_k = _dist_to_line(x, y, line(FPW_KEEP_WAY))
    wz = (ndimage.gaussian_filter(zone.astype(np.float64), 1.5) * zone * smoothstep((d_b - k0) / k1)
          * smoothstep((d_k - FPW_KEEP_M[0]) / (FPW_KEEP_M[1] - FPW_KEEP_M[0])))
    dv = wz * (tgt - hw)
    h = h.copy()
    h[win] = hw + dv
    return h, {"cells": int((np.abs(dv) > 0.01).sum()), "lower": float(-dv.min()), "raise": float(dv.max()),
               "floor": top, "rim": (float(rim_line.min()), float(rim_line.max()))}


def finpark_valley(h, water, pool_w, d_pool, pool, line):
    """Долина Финского парка (finpark_valley, build/finpark_relief/proposal.md) — в абсолютных высотах h, до P-2 и P-4.
    Зона — от берега бьефа VALLEY_BANK до бровки FP_BROW, на западе до FP_WEST. Дно — от уровня бьефа pool: у воды
    низкий берег (FP_FLOOR_EDGE_M), к склону газон pool + FP_FLOOR_M (вверх по реке — выше на FP_FLOOR_UP), у южного
    устоя и схода с моста — не ниже FP_APRON_Z, у нижнего бьефа — наброска FP_LOW_GRADE. Склон — один: от бровки
    (высота — h на линии до правила, скользящее среднее FP_RIM_SMOOTH_M) к дну по smoothstep шириной FP_SLOPE_RUN ×
    перепад. Трассы FP_PATH_Z — по своим отметкам, в полную силу и за краем зоны (только в своём коридоре); под домом
    на склоне (FP_BUILD_KEEP) — прежний рельеф. Снаружи зоны и коридоров рельеф прежний. Возвращает новые h и сводку."""
    r0, r1 = HALF - 160, HALF + 201                  # окно: X от 160 до −200 м
    c0, c1 = HALF + 540, N                           # Y от 540 м до края Landscape
    win = np.s_[r0:r1, c0:c1]
    x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                       indexing="ij")
    hw, wet, dp = h[win], water[win], d_pool[win]
    d_low = ndimage.distance_transform_edt(~(water & ~pool_w))[win]
    brow = line(FP_BROW)                             # с востока на запад: (−78,9; 975,6) … (−86,4; 760,5)
    ring = ([FP_WEST[-1]] + list(VALLEY_BANK) + [(VALLEY_BANK[-1][0], FP_BROW_EAST[0][1])] + list(FP_BROW_EAST)
            + brow + list(FP_WEST[:-1]))
    zone = (_mask(ring, blur=0)[win] > 0.5) & ~wet
    # высота бровки: h на линии через 1 м (за краем Landscape — последнее значение), скользящее среднее
    bl = [FP_WEST[0]] + brow[::-1] + list(FP_BROW_EAST)   # с запада на восток, от верха лестниц к ул. Воровского
    d_b, s_b = _nearest_on_line(x, y, bl)
    P = np.array(bl)
    L = np.r_[0.0, np.cumsum(np.hypot(*np.diff(P, axis=0).T))]
    sl = np.arange(0.0, L[-1], 1.0)
    lx, ly = np.interp(sl, L, P[:, 0]), np.interp(sl, L, P[:, 1])
    ok = ly <= HALF
    rim_line = ndimage.map_coordinates(h, [HALF - lx, np.minimum(ly, HALF) + HALF], order=1)
    rim_line = ndimage.uniform_filter1d(np.where(ok, rim_line, rim_line[ok][-1]), int(FP_RIM_SMOOTH_M), mode="nearest")
    rim = np.interp(s_b, sl, rim_line)
    # дно
    top = pool + FP_FLOOR_M + FP_FLOOR_UP * np.maximum(y - FP_FLOOR_Y0, 0.0)    # газон у подошвы склона
    floor = np.minimum(pool + FP_FLOOR_EDGE_M + FP_FLOOR_GRADE * np.maximum(dp - FP_SHORE_M, 0.0), top)
    d_a = _dist_to_line(x, y, FP_APRON_SEG)
    floor += ((1 - smoothstep((d_a - FP_APRON_M[0]) / (FP_APRON_M[1] - FP_APRON_M[0])))
              * np.maximum(FP_APRON_Z - floor, 0.0))
    shore = pool + POOL_RIM_M + (FP_FLOOR_EDGE_M - POOL_RIM_M) * smoothstep(dp / FP_SHORE_M)
    floor = np.where(dp < FP_SHORE_M, np.minimum(floor, shore), floor)
    floor = np.minimum(floor, WATER_LEVEL_ABS + POOL_RIM_M + FP_LOW_GRADE * d_low)
    # склон: ширина по перепаду бровка — газон, подошва не ближе FP_TOE_WATER_M к воде
    W = np.clip(FP_SLOPE_RUN * (rim - top), *FP_SLOPE_W_M)
    W = np.minimum(W, np.maximum(d_b + dp - FP_TOE_WATER_M, 4.0))
    tgt = floor + np.maximum(rim - floor, 0.0) * smoothstep(1 - d_b / W)
    tgt = np.where(zone, tgt, hw)                    # вне зоны трассы стыкуются с прежним рельефом
    # трассы: отметка по длине — линейно между узлами, поперёк ровно; пересечения — среднее с весом w² (без скачков)
    zsum, wtot, w_path = np.zeros_like(hw), np.zeros_like(hw), np.zeros_like(hw)
    for way, anchors in FP_PATH_Z.items():
        allp = line(way)
        i0 = anchors[0][0]
        p = allp[i0:anchors[-1][0] + 1]
        d, s = _nearest_on_line(x, y, p)
        Lw = np.r_[0.0, np.cumsum(np.hypot(*np.diff(np.array(p), axis=0).T))]
        zz = [z if z is not None else float(tgt[int(round(HALF - allp[i][0])) - r0, int(round(allp[i][1] + HALF)) - c0])
              for i, z in anchors]
        zline = np.interp(s, [Lw[i - i0] for i, _ in anchors], zz)
        w = 1 - smoothstep((d - FP_PATH_HALF_M) / FP_PATH_BLEND_M)
        zsum += w * w * zline
        wtot += w * w
        w_path = np.maximum(w_path, w)
    tgt += w_path * (zsum / np.maximum(wtot, 1e-9) - tgt)
    # дом на склоне — на прежнем рельефе
    for bid in FP_BUILD_KEEP:
        m = _mask(line(bid), blur=0)[win] > 0.5
        dm = ndimage.distance_transform_edt(~m)
        tgt += (1 - smoothstep((dm - FP_BUILD_KEEP_M[0]) / (FP_BUILD_KEEP_M[1] - FP_BUILD_KEEP_M[0]))) * (hw - tgt)
    # вес: зона с мягким краем (1,5 м), у западного края — переход; трассы — в полную силу в своём коридоре
    wz = (ndimage.gaussian_filter(zone.astype(np.float64), 1.5) * zone
          * smoothstep(_dist_to_line(x, y, list(FP_WEST)) / FP_WEST_BLEND_M))
    wz = np.maximum(wz, w_path * ~wet)
    dv = wz * (tgt - hw)
    h = h.copy()
    h[win] = hw + dv
    at = lambda px, py: float(ndimage.map_coordinates(h, [[HALF - px], [py + HALF]], order=1)[0])  # noqa: E731
    return h, {"cells": int((np.abs(dv) > 0.01).sum()), "outside": int(((np.abs(dv) > 0.01) & ~zone).sum()),
               "lower": float(-dv.min()), "raise": float(dv.max()), "alley": at(-3.9, 861.2),
               "stair_low": at(*line(67215712)[0]), "bridge_end": at(*line(66837904)[-1])}


def pool_water(park, h0):
    """Вода выше плотины для landscape_krom: кольцо POOL_RING, раздвинутое на POOL_WATER_PAD_M под берега (у гребня —
    только вдоль гребня в берега), и протока лентой; уровни — м от собора."""
    P = np.array(POOL_RING, dtype=np.float64)
    area = 0.5 * np.sum(P[:, 0] * np.roll(P[:, 1], -1) - np.roll(P[:, 0], -1) * P[:, 1])
    e = np.roll(P, -1, axis=0) - P                       # ребро i: P[i] → P[i+1]
    e /= np.hypot(*e.T)[:, None]
    nrm = np.c_[e[:, 1], -e[:, 0]] * (1.0 if area > 0 else -1.0)  # наружу
    out = []
    for i in range(len(P)):                              # ребро 0 — гребень (−8,4; 714,1) → (29,8; 683,3)
        if i == 0:
            out.append(P[i] - e[0] * POOL_WATER_PAD_M)
        elif i == 1:
            out.append(P[i] + e[0] * POOL_WATER_PAD_M)
        else:
            m = nrm[i - 1] + nrm[i]
            m /= max(np.hypot(*m), 1e-9)
            k = min(POOL_WATER_PAD_M / max(float(np.dot(m, nrm[i])), 0.5), 2 * POOL_WATER_PAD_M)
            out.append(P[i] + m * k)
    return {"script": "scripts/terrain_krom.py", "note": "вода выше плотины Финского парка (P-1, P-4; гип.)",
            "pools": [{"name": "PskovaPool", "z_m": round(park["pool_abs"] - h0, 3),
                       "ring": [[round(float(x), 2), round(float(y), 2)] for x, y in out]}],
            "ribbons": [{"name": "FinparkStream", "z_m": round(park["pool_abs"] - h0, 3),
                         "width_m": STREAM_RIBBON_M, "pts": [list(p) for p in STREAM_PTS]}]}


def okolny_sections():
    """Внешние грани стены Окольного города (okolny_plan.wall_runs) по линиям OSM: [[(x, y, t), …]] — вершины и
    толщина тела на отрезке от вершины (участки, продолжающие друг друга, — одна линия)."""
    import okolny_plan as okolny
    out, cur = [], []
    for r in okolny.wall_runs():
        pts = [tuple(p) for p in r.points]
        if cur and np.hypot(cur[-1][0] - pts[0][0], cur[-1][1] - pts[0][1]) < 0.5:
            cur[-1] = (cur[-1][0], cur[-1][1], r.profile.t)
            cur += [(p[0], p[1], r.profile.t) for p in pts[1:]]
        else:
            if cur:
                out.append(cur)
            cur = [(p[0], p[1], r.profile.t) for p in pts]
    return out + [cur]


def okolny_step(h, water, d_land):
    """Рельеф у стены Окольного города по Великой (D-040) — в абсолютных высотах h. С речной стороны у внешней грани
    земля на okolny_plan.FOOT_Z, ступень с уровня города — посередине тела (OKOLNY_BODY_STEP); к реке газон и верхняя
    набережная полого до края (линии OKOLNY_EMBANKMENTS, OKOLNY_EDGE_Z), уступ OKOLNY_STEP_M к нижней набережной
    (OKOLNY_LOWER_Z) до воды; у уреза и в воде — прежний берег; за концами линий (съезд с моста, Профсоюзная,
    поликлиника) — к прежнему рельефу за OKOLNY_BLEND_M; город за стеной не трогаем. Возвращает новые h и сводку."""
    import okolny_plan as okolny
    h0 = float(h[HALF, HALF])  # земля у собора (правила её не трогают): отметки плана — от неё
    secs = okolny_sections()
    P = np.array([p[:2] for s in secs for p in s])
    m = OKOLNY_REACH_M + OKOLNY_BLEND_M
    r0, r1 = max(int(HALF - P[:, 0].max() - m), 0), min(int(HALF - P[:, 0].min() + m) + 1, N)
    c0, c1 = max(int(P[:, 1].min() - m + HALF), 0), min(int(P[:, 1].max() + m + HALF) + 1, N)
    win = np.s_[r0:r1, c0:c1]
    x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                       indexing="ij")
    d = np.full(x.shape, np.inf)
    w, t, qx, qy, sb = (np.zeros(x.shape) for _ in range(5))  # w — к городу +; sb — от ближнего конца линии, м
    for sec in secs:                                          # (внутри линии < 0, за концом > 0)
        seg = np.hypot(*np.diff(np.array(sec)[:, :2], axis=0).T)
        S, total = np.r_[0.0, np.cumsum(seg)], float(seg.sum())
        for i in range(len(sec) - 1):
            (ax, ay, ta), (bx, by, _) = sec[i], sec[i + 1]
            ex, ey = bx - ax, by - ay
            L = seg[i]
            u = ((x - ax) * ex + (y - ay) * ey) / (L * L)
            uc = np.clip(u, 0.0, 1.0)
            px, py = ax + uc * ex, ay + uc * ey
            dd = np.hypot(x - px, y - py)
            nx, ny = -ey / L, ex / L
            if ny < 0:  # к городу — на восток (Великая к западу от стены)
                nx, ny = -nx, -ny
            s_at = S[i] + (u if i in (0, len(sec) - 2) else uc) * L   # за концами — продолжение линии
            bb = -np.minimum(s_at, total - s_at)
            closer = dd < d
            d = np.where(closer, dd, d)
            w = np.where(closer, (x - ax) * nx + (y - ay) * ny, w)
            t = np.where(closer, ta, t)
            qx, qy, sb = np.where(closer, px, qx), np.where(closer, py, qy), np.where(closer, bb, sb)

    els = {e["id"]: e for e in geo.load_elements(geo.latest("krom_2*.json")) if e["type"] == "way"}
    emb = features.rasterize([{"type": "LineString", "coordinates": [(p[1], p[0]) for p in
                                                                     geo.local_points(els[i]["geometry"]) if p]}
                              for i in OKOLNY_EMBANKMENTS], out_shape=(N, N), transform=MAP_T, fill=0,
                             default_value=1, all_touched=True).astype(bool)
    e_q = ndimage.map_coordinates(ndimage.distance_transform_edt(~emb), [HALF - qx, qy + HALF], order=1)
    edge = e_q <= OKOLNY_EDGE_MAX_M
    foot, top, lower = okolny.FOOT_Z + h0, OKOLNY_EDGE_Z + h0, OKOLNY_LOWER_Z + h0
    r = np.maximum(-w, 0.0)                     # от внешней грани к реке
    e = np.where(edge, e_q, OKOLNY_PLATFORM_M)
    tgt = foot + (top - foot) * np.clip(r / np.maximum(e, 1.0), 0.0, 1.0)
    tgt = np.where(edge, tgt + (lower - tgt) * smoothstep((r - e) / OKOLNY_STEP_M), tgt)
    hw = h[win]
    wgt = ((1 - smoothstep((w - OKOLNY_BODY_STEP * t + 0.5) / 1.0))       # город за ступенью в теле — прежний
           * (1 - smoothstep((sb + OKOLNY_END_IN_M) / OKOLNY_BLEND_M))     # у концов линий — к прежнему
           * (1 - smoothstep((r - OKOLNY_REACH_M + 10.0) / 10.0))
           * np.where(edge, 1.0, 1 - smoothstep((r - e) / OKOLNY_BLEND_M))  # без края набережной — газон и откос
           * smoothstep((d_land[win] - OKOLNY_WATER_M[0]) / (OKOLNY_WATER_M[1] - OKOLNY_WATER_M[0]))
           * ~water[win])
    delta = wgt * (tgt - hw)
    h = h.copy()
    h[win] += delta
    at_face = (d < 1.0) & (sb < -OKOLNY_END_IN_M) & (w <= 0)
    return h, {"cells": int((np.abs(delta) > 0.01).sum()), "lower": float(-delta.min()), "raise": float(delta.max()),
               "face_z": (float((h[win] - h0)[at_face].min()), float((h[win] - h0)[at_face].max())) if at_face.any()
               else None}


def mstislav_foot(h, water):
    """Рельеф у Мстиславской башни (D-040) — в абсолютных высотах h; продолжение okolny_step вокруг башни. Линия ступени
    в теле стены (OKOLNY_BODY_STEP, отрезок стены у башни) продолжена через башню: с речной стороны земля срезается до
    okolny_plan.FOOT_Z (только срезка — ниже неё рельеф прежний), вдоль стены до MST_FULL_M за контуром башни — в полную
    силу, дальше к прежнему за MST_BLEND_M. Со стороны стены ступень резкая (в теле, как в okolny_step), за башней —
    откос шириной MST_SIDE_M с речной стороны линии. Город за линией не трогаем. Возвращает новые h и сводку."""
    import okolny_plan as okolny
    h0 = float(h[HALF, HALF])
    tower = okolny.MSTISLAVSKAYA
    cx, cy = tower.origin
    R = max(float(np.hypot(p[0] - cx, p[1] - cy)) for p in tower.footprint)
    # отрезок стены у башни: конец линии, ближайший к ней; толщина тела — у вершины, с которой отрезок начинается
    ends = [(sec[-1], sec[-2], sec[-2][2]) for sec in okolny_sections()] + \
           [(sec[0], sec[1], sec[0][2]) for sec in okolny_sections()]
    (bx, by, _), (ax, ay, _), t = min(ends, key=lambda e: np.hypot(e[0][0] - cx, e[0][1] - cy))
    L = float(np.hypot(bx - ax, by - ay))
    ux, uy = (bx - ax) / L, (by - ay) / L             # вдоль стены к башне и дальше
    nx, ny = -uy, ux
    if ny < 0:  # к городу — на восток, как в okolny_step
        nx, ny = -nx, -ny
    m = R + MST_FULL_M + MST_BLEND_M + OKOLNY_REACH_M + 2.0
    r0, r1 = max(int(HALF - cx - m), 0), min(int(HALF - cx + m) + 1, N)
    c0, c1 = max(int(cy - m + HALF), 0), min(int(cy + m + HALF) + 1, N)
    win = np.s_[r0:r1, c0:c1]
    x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                       indexing="ij")
    a = (x - cx) * ux + (y - cy) * uy                            # от центра башни вдоль стены: за башней > 0
    v = OKOLNY_BODY_STEP * t - ((x - ax) * nx + (y - ay) * ny)   # от линии ступени к реке, м
    width = 1.0 + (MST_SIDE_M - 1.0) * smoothstep(a / R)         # у стены ступень резкая, за башней — откос
    wgt = (smoothstep((v + 0.5) / width)
           * (1 - smoothstep((np.abs(a) - R - MST_FULL_M) / MST_BLEND_M))
           * (1 - smoothstep((v - OKOLNY_REACH_M + 10.0) / 10.0))
           * ~water[win])
    hw = h[win]
    delta = wgt * np.minimum(okolny.FOOT_Z + h0 - hw, 0.0)
    h = h.copy()
    h[win] += delta
    rho = np.hypot(x - cx, y - cy)
    ring = (rho > R + 0.5) & (rho < R + 1.5) & (wgt > 0.99)          # у подошвы с речной стороны
    return h, {"cells": int((np.abs(delta) > 0.01).sum()), "lower": float(-delta.min()),
               "foot_z": (float((h[win] - h0)[ring].min()), float((h[win] - h0)[ring].max())) if ring.any() else None}


def _outside(x, y, ring):
    """Расстояние от узлов (x, y) до многоугольника ring снаружи, м; внутри — 0."""
    from matplotlib.path import Path
    ring = [tuple(p) for p in ring]
    inside = Path(ring).contains_points(np.c_[x.ravel(), y.ravel()]).reshape(x.shape)
    return np.where(inside, 0.0, _dist_to_line(x, y, ring + ring[:1]))


def church_ground(h, water, d_land, d_wall, roads):
    """Рельеф у храмов генератора (VASILY_*, USOKHA_*, BOG_*, PRED_*) — в абсолютных высотах h, до road_bed.
    Василий на Горке — горка (подошва на VASILY_HILL_M над heightmap) с мостовой у колокольни, только насыпь; Никола со
    Усохи — двор с запада, севера и юга ниже на USOKHA_PIT_M до подпорных стенок, четверик и полоса апсид прежние,
    проезжая часть OSM (roads — линии и ширины слоя Road) — на уровне улицы;
    Богоявления — площадка под храмом и звонницей на отметке северной стороны, к югу откос; Предтеченский — газон и
    улица к востоку вровень с землёй в центре, только насыпь. Уровни — от земли в ground_at до правила. У стен ближе
    WALL_KEEP_M и у воды (CHURCH_KEEP_WATER_M) рельеф прежний. Возвращает новые h и сводку по храмам: база героя
    (земля в ground_at) до и после, земля у подошвы (в 1 м за контуром) от новой базы, z_foot плана, число клеток."""
    h0, h = h, h.copy()

    def z_at(a, p):
        return float(ndimage.map_coordinates(a, [[HALF - p[0]], [p[1] + HALF]], order=1)[0])

    def window(plan, pad):
        cx, cy = plan.center
        r0, r1 = max(int(HALF - cx - pad), 0), min(int(HALF - cx + pad) + 1, N)
        c0, c1 = max(int(cy - pad + HALF), 0), min(int(cy + pad + HALF) + 1, N)
        win = np.s_[r0:r1, c0:c1]
        x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                           indexing="ij")
        t = np.radians(plan.yaw)
        u = (x - cx) * np.cos(t) + (y - cy) * np.sin(t)
        v = -(x - cx) * np.sin(t) + (y - cy) * np.cos(t)
        a, b = CHURCH_KEEP_WATER_M
        keep = (~water[win] * smoothstep((d_land[win] - a) / (b - a))
                * smoothstep((d_wall[win] - WALL_KEEP_M[0]) / (WALL_KEEP_M[1] - WALL_KEEP_M[0])))
        return win, x, y, u, v, keep

    out = {}

    def summary(key, plan, bld, win, x, y, g):
        base = z_at(h, bld.ground_at)
        d = _outside(x, y, bld.footprint)
        foot = (d > 0) & (d <= 1.0)
        dh = h[win] - h0[win]
        out[key] = {"g": g, "base": base, "z_foot": plan.z_foot, "cells": int((np.abs(dh) > 0.01).sum()),
                    "foot": (float((h[win] - base)[foot].min()), float((h[win] - base)[foot].max()))}

    # Василий на Горке: к востоку от VASILY_STEP_U — горка, к западу — мостовая; склон к прежнему рельефу
    p = krom_plan.VASILY
    bld = krom_plan.pskov_church(p)
    win, x, y, u, v, keep = window(p, 50.0)
    g = z_at(h0, bld.ground_at)
    s = smoothstep((u - VASILY_STEP_U[0]) / (VASILY_STEP_U[1] - VASILY_STEP_U[0]))
    level = g + VASILY_PAVE_M + (VASILY_HILL_M - VASILY_PAVE_M) * s
    apron = VASILY_PAVE_APRON_M + (VASILY_TOP_M - VASILY_PAVE_APRON_M) * s
    w = (1 - smoothstep((_outside(x, y, bld.footprint) - apron) / VASILY_SLOPE_M)) * keep
    h[win] += w * np.maximum(level - h[win], 0.0)
    summary("Василий", p, bld, win, x, y, g)

    # Никола со Усохи: дно двора — в прямоугольнике до подпорных стенок, кроме четверика и полосы апсид к востоку
    p = krom_plan.USOKHA
    bld = krom_plan.pskov_church(p)
    win, x, y, u, v, keep = window(p, 45.0)
    g = z_at(h0, bld.ground_at)
    (uw, vn), (_, vs) = np.min(p.outline(), axis=0), np.max(p.outline(), axis=0)
    mw, mn, ms = USOKHA_YARD_M
    e = np.maximum(np.maximum(uw - mw - u, u - USOKHA_PIT_E_U), np.maximum(vn - mn - v, v - vs - ms))
    pit = 1 - smoothstep(e / USOKHA_WALL_M)
    d_road = np.full(x.shape, np.inf)
    for line, width in roads:
        (lx0, ly0), (lx1, ly1) = np.min(line, axis=0), np.max(line, axis=0)
        if lx0 < x.max() + 10 and lx1 > x.min() - 10 and ly0 < y.max() + 10 and ly1 > y.min() - 10:  # рамка окна
            d_road = np.minimum(d_road, _dist_to_line(x, y, line) - width / 2)
    pit *= smoothstep((d_road - USOKHA_ROAD_M) / USOKHA_WALL_M)
    u0, u1, v0, v1 = p.quad
    band = [(a.v0, a.v1) for a in p.apses if a.v0 >= v0 and a.v1 <= v1]  # апсиды четверика (не придела)
    b0, b1 = min(a for a, _ in band), max(b for _, b in band)
    inner = np.maximum(np.minimum.reduce([u - u0, u1 - u, v - v0, v1 - v]),  # в четверике, м от грани
                       np.minimum.reduce([u, v - b0, b1 - v]))               # и в полосе апсид к востоку
    a, b = USOKHA_STEP_IN_M
    h[win] -= USOKHA_PIT_M * pit * (1 - smoothstep((inner - a) / (b - a))) * keep
    summary("Никола со Усохи", p, bld, win, x, y, g)

    # Богоявления: площадка под храмом и звонницей (выпуклая оболочка контуров) на отметке северной стороны
    p = krom_plan.BOGOYAVLENIE
    bld = krom_plan.pskov_church(p)
    bel = krom_plan.pskov_belfry(krom_plan.BOGOYAVLENIE_BELFRY)
    win, x, y, u, v, keep = window(p, 50.0)
    g = z_at(h0, bld.ground_at)
    hull = krom_plan.convex_hull(list(bld.footprint) + list(bel.footprint))
    bn, bs = BOG_BLEND_M
    blend = bn + (bs - bn) * smoothstep((v + 8.0) / 16.0)  # v — к югу
    w = (1 - smoothstep((_outside(x, y, hull) - BOG_APRON_M) / blend)) * keep
    h[win] += w * (g + BOG_LIFT_M - h[win])
    summary("Богоявления", p, bld, win, x, y, g)
    out["Богоявления"]["belfry"] = (z_at(h0, bel.ground_at), z_at(h, bel.ground_at))

    # Предтеченский: газон и улица у храма — не ниже земли в центре
    p = krom_plan.PREDTECHA
    bld = krom_plan.pskov_church(p)
    win, x, y, u, v, keep = window(p, 45.0)
    g = z_at(h0, bld.ground_at)
    w = (1 - smoothstep((_outside(x, y, bld.footprint) - PRED_APRON_M) / PRED_BLEND_M)) * keep
    h[win] += w * np.maximum(g - h[win], 0.0)
    summary("Предтеченский", p, bld, win, x, y, g)
    return h, out


def oktyabrskaya_ground(h, water, d_land, d_wall):
    """Октябрьская площадь и амфитеатр Детского парка (OKT_*, AMPH_*) — в абсолютных высотах h, после church_ground
    (горку Василия на Горке в ≈100 м не трогаем) и до road_bed (обе площадки — за зоной roads_mesh.ZONE_M). Площадка
    у памятника княгине Ольге (контур OSM + extra, газоны тоже) — плоскость OKT_PLAZA_Z у оси памятника с уклоном
    OKT_PLAZA_GRADE, за контуром к прежнему рельефу за OKT_PLAZA_BLEND_M; к западу от OKT_WEST_Y (тротуар ул. Советской) —
    уступ OKT_WEST_STEP_M вниз и переход не шире OKT_WEST_BLEND_M. Амфитеатр (оси landmarks_plan.AMPH: u — к среднему
    проходу): мощёная площадка перед рядами — плоскость AMPH_STAGE_Z; под рядами — пандус на AMPH_UNDER_M ниже задней
    кромки каждой террасы модели SM_Mark_Amphitheatre (терраса ряда k — AMPH_STAGE_Z + AMPH_RISE (k + 1)); за верхним
    рядом — бровка вровень с ним, к прежнему за AMPH_BERM_M; вокруг площадки, по бокам сектора и перед первым рядом —
    переход AMPH_SIDE_M. Насыпь и срезка; у стен и воды — как в church_ground. Возвращает новые h и сводку."""
    import landmarks_plan as lp
    h0, h = h, h.copy()
    z0 = float(h[HALF, HALF])  # земля у собора: OKT_*, AMPH_* — от неё

    def window(x0, x1, y0, y1):
        r0, r1 = max(int(HALF - x1), 0), min(int(HALF - x0) + 1, N)
        c0, c1 = max(int(y0 + HALF), 0), min(int(y1 + HALF) + 1, N)
        win = np.s_[r0:r1, c0:c1]
        x, y = np.meshgrid(HALF - np.arange(r0, r1, dtype=np.float64), np.arange(c0, c1, dtype=np.float64) - HALF,
                           indexing="ij")
        a, b = CHURCH_KEEP_WATER_M
        keep = (~water[win] * smoothstep((d_land[win] - a) / (b - a))
                * smoothstep((d_wall[win] - WALL_KEEP_M[0]) / (WALL_KEEP_M[1] - WALL_KEEP_M[0])))
        return win, x, y, keep

    out = {}
    # площадка у памятника: плоскость через ось памятника; за контуром — та же плоскость (с запада — на уступ ниже)
    outer = {s[0]: s for s in osm_layers.squares()}[OKT_PLAZA][2]
    pts = np.concatenate([np.asarray(r, dtype=np.float64) for r in outer])
    pad = max(OKT_PLAZA_BLEND_M, OKT_WEST_BLEND_M) + 2.0
    win, x, y, keep = window(pts[:, 0].min() - pad, pts[:, 0].max() + pad, pts[:, 1].min() - pad, pts[:, 1].max() + pad)
    d = np.minimum.reduce([_outside(x, y, r) for r in outer])
    t = np.radians(OKT_PLAZA_UP_AZ)
    plane = z0 + OKT_PLAZA_Z + OKT_PLAZA_GRADE * ((x - lp.OLGA_XY[0]) * np.cos(t) + (y - lp.OLGA_XY[1]) * np.sin(t))
    west = smoothstep(OKT_WEST_Y - y)
    tgt = np.where(d > 0, plane - OKT_WEST_STEP_M * west, plane)
    w = (1 - smoothstep(d / (OKT_PLAZA_BLEND_M + (OKT_WEST_BLEND_M - OKT_PLAZA_BLEND_M) * west))) * keep
    h[win] += w * (tgt - h[win])
    dh = h[win] - h0[win]
    out["plaza"] = {"z": (float(h[win][d == 0].min() - z0), float(h[win][d == 0].max() - z0)),
                    "raise": float(dh.max()), "lower": float(-dh.min()), "cells": int((np.abs(dh) > 0.01).sum())}

    # амфитеатр: площадка, пандус под рядами, бровка за верхним рядом
    cx, cy = lp.AMPH_CENTER
    t = np.radians(lp.AMPH_YAW)
    r_front = AMPH_R0 - AMPH_EDGE                      # подступенок первого ряда
    r_back = AMPH_R0 + AMPH_PITCH * AMPH_ROWS - AMPH_EDGE  # задняя кромка верхнего ряда
    m = r_back + AMPH_BERM_M + 2.0
    win, x, y, keep = window(cx - m, cx + m, cy - m, cy + m)
    u = (x - cx) * np.cos(t) + (y - cy) * np.sin(t)
    v = -(x - cx) * np.sin(t) + (y - cy) * np.cos(t)
    r = np.hypot(u, v)
    side = (np.abs(np.arctan2(v, u)) - np.radians(AMPH_SECTOR_DEG)) * r  # за краем сектора, м по дуге
    z_st, top = z0 + AMPH_STAGE_Z, z0 + AMPH_STAGE_Z + AMPH_RISE * AMPH_ROWS
    ramp = z_st + AMPH_RISE * np.clip((r - r_front) / AMPH_PITCH, 0, AMPH_ROWS) - AMPH_UNDER_M
    tgt = np.where(r < r_front, z_st, np.where(r <= r_back, ramp, top))
    w_stage = 1 - smoothstep(_outside(u, v, lp.amph_stage_uv()) / AMPH_SIDE_M)
    w_rows = ((1 - smoothstep((r - r_back) / AMPH_BERM_M)) * (1 - smoothstep(side / AMPH_SIDE_M))
              * smoothstep((r - r_front + AMPH_SIDE_M) / AMPH_SIDE_M))
    w = np.maximum(w_stage, w_rows) * keep
    h[win] += w * (tgt - h[win])
    dh = h[win] - h0[win]
    out["amph"] = {"stage": z_st - z0, "top": top - z0, "raise": float(dh.max()), "lower": float(-dh.min()),
                   "cells": int((np.abs(dh) > 0.01).sum())}
    return h, out


def road_bed(h, water, wall, d_land):
    """Рельеф под лентами roads_mesh в зоне roads_mesh.ZONE_M (D-038) — в абсолютных высотах h.

    Коридоры — roads_mesh.corridors по этому же рельефу (профиль оси: сглаженный рельеф, концы — в узлах). Проезжая
    часть: на полуширину — ровно поперёк, на ROAD_SINK_M ниже профиля; за краем полоса бордюра (band) на его высоте;
    дальше переход к прежнему рельефу за ROAD_BLEND_M (1:3 при большой разнице). Дорожки: на полуширину + PATH_CORE_M —
    на PATH_SINK_M ниже, переход PATH_BLEND_M. Сначала дорожки, потом проезжая часть; в своих полосах дорожки
    проезжая часть не перебивает (кроме самого полотна). За концами линий (у мостов, тупики) коридор не продолжается.
    Набережная Псковы — терраса (pskova_terrace), её здесь нет. У стен (WALL_KEEP_M; у западной стены Довмонтова
    города — WALL_KEEP_EXCEPT), под зданиями плана и героями (BED_KEEP_BUILDING_M), у воды (BED_KEEP_WATER_M), в воде
    и у края зоны рельеф прежний. Возвращает новые h и сводку."""
    import roads_mesh

    def z_at(p):
        p = np.asarray(p, dtype=np.float64).reshape(-1, 2)
        return ndimage.map_coordinates(h, [HALF - p[:, 0], p[:, 1] + HALF], order=1, mode="nearest")

    cors = roads_mesh.corridors(z_at, exclude=(TERRACE_WAY,), water=WATER_LEVEL_ABS)
    feet = [{"type": "Polygon", "coordinates": [[(p[1], p[0]) for p in b.footprint] + [(b.footprint[0][1],
                                                                                        b.footprint[0][0])]]}
            for b in krom_plan.towers() + krom_plan.buildings() if getattr(b, "footprint", None)]
    under = features.rasterize(feet, out_shape=(N, N), transform=MAP_T, fill=0, default_value=1,
                               all_touched=True).astype(bool)
    # стены: у участка-исключения — своя охрана, у прочих — WALL_KEEP_M (их линии OSM у исключения не считаем)
    names, (e0, e1) = WALL_KEEP_EXCEPT
    line = features.rasterize([{"type": "LineString", "coordinates": [(p[1], p[0]) for p in run.points]}
                               for run in krom_plan.wall_runs() if run.name in names],
                              out_shape=(N, N), transform=MAP_T, fill=0, default_value=1, all_touched=True).astype(bool)
    d_run = ndimage.distance_transform_edt(~line)
    # стена Окольного города (okolny_step): WALL_KEEP_M не действует, охраняется только тело (OKOLNY_BODY_KEEP_M)
    okl = features.rasterize([{"type": "LineString", "coordinates": [(p[1], p[0]) for p in sec]}
                              for sec in okolny_sections()], out_shape=(N, N), transform=MAP_T, fill=0,
                             default_value=1, all_touched=True).astype(bool)
    d_okl = ndimage.distance_transform_edt(~okl)
    d_other = ndimage.distance_transform_edt(~(wall & (d_run > WALL_EXCEPT_STRIP_M) & (d_okl > WALL_EXCEPT_STRIP_M)))
    keep_wall = (smoothstep((d_other - WALL_KEEP_M[0]) / (WALL_KEEP_M[1] - WALL_KEEP_M[0]))
                 * smoothstep((d_run - e0) / (e1 - e0))
                 * smoothstep((d_okl - OKOLNY_BODY_KEEP_M[0]) / (OKOLNY_BODY_KEEP_M[1] - OKOLNY_BODY_KEEP_M[0])))
    a, b = BED_KEEP_BUILDING_M
    keep = (keep_wall * ~water
            * smoothstep((ndimage.distance_transform_edt(~under) - a) / (b - a))
            * smoothstep((d_land - BED_KEEP_WATER_M[0]) / (BED_KEEP_WATER_M[1] - BED_KEEP_WATER_M[0])))
    x = (HALF - np.arange(N, dtype=np.float64))[:, None]
    y = (np.arange(N, dtype=np.float64) - HALF)[None, :]
    zone = roads_mesh.zone_weight(x, y, ROAD_ZONE_FADE_M)   # весь Landscape, гаснет у кромки (roads_mesh.ZONE_M)
    out, core_path = h.copy(), np.zeros((N, N), bool)
    info = {"car": sum(c["group"] == "car" for c in cors), "path": sum(c["group"] == "path" for c in cors)}
    for group, sink, extra, (bmin, bmax) in (("path", roads_mesh.PATH_SINK_M, PATH_CORE_M, PATH_BLEND_M),
                                             ("car", roads_mesh.ROAD_SINK_M, 0.0, ROAD_BLEND_M)):
        cap = BED_MAX_M[group]
        items = [c for c in cors if c["group"] == group]
        if not items:
            continue
        pts = np.concatenate([c["pts"] for c in items])
        per = lambda key: np.concatenate([np.full(len(c["pts"]), c[key]) for c in items])  # noqa: E731
        z, half, kerb, band = np.concatenate([c["z"] for c in items]), per("half"), per("kerb"), per("band")
        allow = np.concatenate([c["allow"] for c in items])
        caps = np.concatenate([np.full(len(c["pts"]), BED_MAX_M["car"] if c["half"] * 2 >= BED_WIDE_PATH_M else cap)
                               for c in items])
        # концы: наружное направление у первой и последней станции (за концом коридор не продолжается)
        out_dir = np.zeros_like(pts)
        i0 = 0
        for c in items:
            q = c["pts"]
            for i, j in ((0, 1), (len(q) - 1, len(q) - 2)):
                t = q[i] - q[j]
                out_dir[i0 + i] = t / (np.hypot(*t) or 1.0)
            i0 += len(q)
        rr, cc = np.rint(HALF - pts[:, 0]).astype(int), np.rint(pts[:, 1] + HALF).astype(int)
        ok = np.nonzero((rr >= 0) & (rr < N) & (cc >= 0) & (cc < N))[0]
        ok = ok[np.argsort(np.hypot(*out_dir[ok].T) == 0, kind="stable")]  # в общей клетке узла — не конец линии
        idx = np.zeros((N, N), np.int64)
        idx[rr[ok], cc[ok]] = ok + 1
        dist, (ii, jj) = ndimage.distance_transform_edt(idx == 0, return_indices=True)
        k = idx[ii, jj] - 1
        zk, kk = z[k], kerb[k]
        core = half[k] + extra
        edge = core + np.where(kk > 0, band[k], 0.0)
        edge_z = np.where(kk > 0, zk + kk, zk - sink)
        tgt = np.where(dist <= core, zk - sink, edge_z)
        lim = caps[k] + allow[k]  # у подъездов к мостам — насыпь до настила
        tgt = out + np.clip(tgt - out, -lim, lim)
        blend = np.clip(3.0 * np.abs(tgt - out), bmin, bmax)
        w = np.where(dist <= edge, 1.0, 1 - smoothstep((dist - edge) / blend)) * zone * keep
        w = np.where(dist <= edge + bmax, w, 0.0)
        beyond = (x - pts[k, 0]) * out_dir[k, 0] + (y - pts[k, 1]) * out_dir[k, 1]
        w = w * (1 - smoothstep((beyond - 0.5) / 1.0))
        if group == "car":
            w = np.where(core_path & (dist > core), 0.0, w)
        else:
            core_path = (dist <= core) & (w > 0.5)
        out = out + w * (tgt - out)
    delta = out - h
    info.update(cells=int((np.abs(delta) > 0.01).sum()), raise_=float(delta.max()), lower=float(-delta.min()))
    info["raise"] = info.pop("raise_")
    return out, info


def build():
    ensure_dem_crop()
    water_geoms, wall_geoms, walls, polys, lines = osm_shapes()
    water = features.rasterize(water_geoms, out_shape=(N, N), transform=MAP_T, fill=0, default_value=1).astype(bool)
    wall = features.rasterize(wall_geoms, out_shape=(N, N), transform=MAP_T, fill=0, default_value=1,
                              all_touched=True).astype(bool)
    dem, dem_water = sample_dem()

    d_land = ndimage.distance_transform_edt(~water)  # суша → до воды, м
    d_water = ndimage.distance_transform_edt(water)  # вода → до берега, м
    d_dem_water = ndimage.distance_transform_edt(~dem_water)
    trust = smoothstep((np.minimum(d_land, d_dem_water) - TRUST_FROM_M) / TRUST_RAMP_M)
    top = np.maximum(plateau(dem, trust), WATER_LEVEL_ABS + SHORE_RIM_M + 0.5)

    # подножие откоса: у западной стены Крома — берма (D-029)
    zone = shore_zone()
    berm = ndimage.gaussian_filter(zone.astype(float), BERM_BLEND_M)
    # ширина откоса: у стен — так, чтобы бровка пришлась на стену
    d_wall, (iw, jw) = ndimage.distance_transform_edt(~wall, return_indices=True)
    room = d_land[iw, jw] - BANK_MIN_M - WALL_MARGIN_M  # сколько подножия умещается до стены
    toe = TOE_M + (np.clip(room, TOE_M, BERM_M) - TOE_M) * berm
    bank_at_wall = np.clip(d_land[iw, jw] - toe[iw, jw] - WALL_MARGIN_M, BANK_MIN_M, BANK_M)
    f = 1 - smoothstep(d_wall / WALL_INFLUENCE_M)
    # сглаживаем: там, где ближайшей становится другая стена, ширина иначе меняется скачком — рубец на склоне
    bank = ndimage.gaussian_filter(f * bank_at_wall + (1 - f) * BANK_M, BANK_SMOOTH_M)

    rim = WATER_LEVEL_ABS + SHORE_RIM_M
    lift = BERM_H_M * berm * smoothstep(d_land / toe)  # берма: от уреза на BERM_H_M к подножию откоса
    land = rim + lift + np.maximum(top - rim - lift, 0) * smoothstep((d_land - toe) / bank)
    bed = WATER_LEVEL_ABS - (SHORE_BED_M + (RIVER_DEPTH_M - SHORE_BED_M) * smoothstep(d_water / BED_WIDTH_M))
    h = ndimage.gaussian_filter(np.where(water, bed, land), 1.0)
    h_street = float(ndimage.map_coordinates(h, [[HALF - HOLY_STREET[0]], [HOLY_STREET[1] + HALF]], order=1)[0])
    h, persi = persi_step(h)
    h = holy_gate(h, h_street)
    h, terrace, riprap = pskova_terrace(h, water, d_land, d_wall)
    h, okolny = okolny_step(h, water, d_land)
    h, mst = mstislav_foot(h, water)
    h, under = underpass(h)
    h, park = finpark(h, water, d_land)
    h, churches = church_ground(h, water, d_land, d_wall, lines["Road"])
    h, okt = oktyabrskaya_ground(h, water, d_land, d_wall)
    h, bed = road_bed(h, water, wall, d_land)

    h0 = float(h[HALF, HALF])  # земля у собора → Z = 0
    print(f"Перси: земля двора {persi['yard'] - h0:+.2f} м, подошва {persi['yard'] - h0 + PERSI_FOOT_M:+.2f}, "
          f"газон {persi['yard'] - h0 + PERSI_LAWN_M:+.2f}, ворота {persi['yard'] - h0 + GATE_M:+.2f} (от собора)")
    print(f"Терраса Псковы: у моста 2024 г. {TERRACE_ABS - h0:+.2f} м на {terrace['flat_m']} м, дальше "
          f"{TERRACE_BASE_ABS - h0:+.2f} на {terrace['base_m']} м из {terrace['len_m']:.0f}; земля поднята до "
          f"{terrace['rise_max']:.1f} м, опущена до {terrace['lower_max']:.1f} м")
    print(f"Стена Окольного города (D-040): изменено {okolny['cells']} клеток 1 м, срезка до {okolny['lower']:.1f} м, "
          f"подъём до {okolny['raise']:.1f} м; земля у внешней грани {okolny['face_z'][0]:+.2f}…"
          f"{okolny['face_z'][1]:+.2f} (от собора)")
    print(f"Мстиславская башня: изменено {mst['cells']} клеток 1 м, срезка до {mst['lower']:.1f} м; земля у подошвы "
          f"с речной стороны {mst['foot_z'][0]:+.2f}…{mst['foot_z'][1]:+.2f} (от собора)")
    for name, c in churches.items():
        print(f"{name} (church_ground): база {c['g'] - h0:+.2f} → {c['base'] - h0:+.2f} (от собора), земля у подошвы "
              f"{c['foot'][0]:+.2f}…{c['foot'][1]:+.2f} от базы (z_foot {c['z_foot']:+.1f}), клеток {c['cells']}"
              + (f"; звонница {c['belfry'][0] - h0:+.2f} → {c['belfry'][1] - h0:+.2f}" if "belfry" in c else ""))
    p, a = okt["plaza"], okt["amph"]
    print(f"Октябрьская площадь (oktyabrskaya_ground): площадка у памятника {p['z'][0]:+.2f}…{p['z'][1]:+.2f} (от "
          f"собора), подсыпка до {p['raise']:.2f} м, срезка до {p['lower']:.2f}, клеток {p['cells']}; амфитеатр: "
          f"площадка {a['stage']:+.2f}, верхний ряд {a['top']:+.2f}, подсыпка до {a['raise']:.2f} м, срезка до "
          f"{a['lower']:.2f}, клеток {a['cells']}")
    print(f"Набережная под Ольгинским мостом: дорожка не выше {under:+.2f} (от собора)" if under is not None else
          "Набережная под Ольгинским мостом: пересечения нет")
    print(f"Под дорогами и дорожками (D-038): {bed['car']} коридоров проезжей части, {bed['path']} дорожек; изменено "
          f"{bed['cells']} клеток 1 м, подъём до {bed['raise']:.2f} м, срезка до {bed['lower']:.2f} м")
    print(f"Финский парк: верхний бьеф {park['pool_abs'] - h0:+.2f} (от собора), суша у него поднята в "
          f"{park['pool_rim_cells']} клетках")
    w = park["west"]
    print(f"Долина Псковы от Советского моста (finpark_west): изменено {w['cells']} клеток 1 м, срезка до "
          f"{w['lower']:.1f} м, подъём до {w['raise']:.1f} м; дно {w['floor']:.2f}, бровка (Милицейская улица) "
          f"{w['rim'][0]:.1f}…{w['rim'][1]:.1f} м абс.")
    v = park["valley"]
    print(f"Долина Финского парка (finpark_valley): изменено {v['cells']} клеток 1 м (за зоной — {v['outside']}, "
          f"коридоры трасс), срезка до {v['lower']:.1f} м, подъём до {v['raise']:.1f} м; аллея у (−3,9; 861,2) "
          f"{v['alley']:.2f}, низ лестницы {v['stair_low']:.2f}, южный конец моста {v['bridge_end']:.2f} м абс.")
    return {"z": h - h0, "h0": h0, "park": park, "dem_z": dem - h0, "water": water, "walls": walls, "polys": polys,
            "lines": lines,
            "shore_zone": zone, "pskova_riprap": riprap}


def shore_zone():
    """Зона берега под западной стеной Крома на сетке рельефа (D-029): не дальше SHORE_ZONE_M от участков SHORE_RUNS
    и ближе к ним, чем к SHORE_NOT."""
    def dist_to(prefixes):
        geoms = [{"type": "LineString", "coordinates": [(p[1], p[0]) for p in run.points]}
                 for run in krom_plan.wall_runs() if run.name.startswith(prefixes)]
        lines = features.rasterize(geoms, out_shape=(N, N), transform=MAP_T, fill=0, default_value=1,
                                   all_touched=True).astype(bool)
        return ndimage.distance_transform_edt(~lines)

    d_near, d_far = dist_to(SHORE_RUNS), dist_to(SHORE_NOT)
    x = HALF - np.arange(N)[:, None]
    y = np.arange(N)[None, :] - HALF
    (ax, ay), (bx, by) = SHORE_WEST_OF
    west = (bx - ax) * (y - ay) - (by - ay) * (x - ax) < 0
    return (d_near <= SHORE_ZONE_M) & (d_near < d_far) & (west | (x < ax))


