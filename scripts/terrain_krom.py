def render_map(polys, lines):
    """Карта OSM на всю площадь Landscape; рисуем с двойным разрешением и уменьшаем (сглаживание)."""
    from PIL import Image, ImageDraw

    def srgb(c):
        return tuple(int(round(255 * v ** (1 / 2.2))) for v in c)

    n = MAP_PX * 2
    k = n / (2 * HALF)  # пикселей на метр
    img = Image.new("RGB", (n, n), srgb(osm_layers.GROUND_COLOR))
    draw = ImageDraw.Draw(img)

    def px(p):  # (x, y) → (столбец, строка), север вверху
        return (p[1] + HALF) * k, (HALF - p[0]) * k

    for name, rgb in osm_layers.LAYERS.items():
        color = srgb(rgb)
        for ring in polys[name]:
            if len(ring) > 2:
                draw.polygon([px(p) for p in ring], fill=color)
        for line, w in lines[name]:
            draw.line([px(p) for p in line], fill=color, width=max(1, round(w * k)), joint="curve")
    img = img.resize((MAP_PX, MAP_PX), Image.LANCZOS)
    ue = np.asarray(img)[::-1, :, :].transpose(1, 0, 2)  # как heightmap: строки — Y, столбцы — X
    Image.fromarray(np.ascontiguousarray(ue)).save(OUT_MAP)


def shore_band(r, n):
    """Индексы классов полосы у уреза и наброски на сетке маски n × n (D-029): (shore, riprap) — булевы массивы."""
    k = n / (2 * HALF)
    rows = (np.arange(n) + 0.5) / k                     # строка маски → строка сетки рельефа (1 м)
    rr, cc = np.meshgrid(rows, rows, indexing="ij")
    wl = WATER_LEVEL_ABS - r["h0"]
    hz = ndimage.map_coordinates(r["z"], [rr, cc], order=1) - wl          # высота над урезом, м
    water = ndimage.map_coordinates(r["water"].astype(np.uint8), [rr, cc], order=0).astype(bool)
    d_water = ndimage.distance_transform_edt(~water) / k                  # до воды, м
    x, y = HALF - rr, cc - HALF
    zone = ndimage.map_coordinates(r["shore_zone"].astype(np.uint8), [rr, cc], order=0).astype(bool)

    noise = ndimage.gaussian_filter(np.random.default_rng(29).standard_normal((n, n)), SHORE_NOISE_M * k / 2)
    noise = (noise - noise.min()) / (noise.max() - noise.min())
    width = SHORE_W_M * (0.55 + 0.9 * noise)
    land = ~water
    shore = land & zone & (d_water <= width) & (hz <= SHORE_H_M)
    riprap = (land & (np.hypot(x - RIPRAP_AT[0], y - RIPRAP_AT[1]) <= RIPRAP_R_M)
              & (d_water <= RIPRAP_W_M) & (hz <= RIPRAP_H_M))
    # камень у уреза под бермой набережной Псковы (pskova_terrace)
    riprap |= land & ndimage.map_coordinates(r["pskova_riprap"].astype(np.uint8), [rr, cc], order=0).astype(bool)
    return shore, riprap


def render_mask(r):
    """Две маски покрытия (osm_layers.ground + полоса у уреза) на всю площадь Landscape: доля класса в пикселе,
    каналы — по GROUND (первая) и GROUND2 (вторая, D-029).

    Все классы рисуются индексами в одну картинку с двойным разрешением (поздний перекрывает ранний, порядок —
    osm_layers.PAINT), поэтому доли всех восьми каналов в сумме не больше 1; доля — среднее по 2 × 2. Площадки
    и площади-мультиполигоны (с дырами газонов), потом полоса у уреза и наброска (только поверх травы и грунта), потом
    линии дорог и троп, здания — поверх всего."""
    from PIL import Image, ImageDraw

    m = HALF + 50
    polys, lines = osm_layers.ground((-m, m, -m, m))
    classes = osm_layers.GROUND + osm_layers.GROUND2
    index = {c: i for i, c in enumerate(classes, start=1)}
    n = MAP_PX * 2
    k = n / (2 * HALF)

    def px(p):
        return (p[1] + HALF) * k, (HALF - p[0]) * k

    img = Image.new("L", (n, n), 0)
    draw = ImageDraw.Draw(img)
    for cls in osm_layers.PAINT:
        for ring in polys[cls]:
            if len(ring) > 2:
                draw.polygon([px(p) for p in ring], fill=index[cls])
    # площади-мультиполигоны (osm_layers.squares: площадь Ленина) — мощение с дырами газонов и клумб; линии дорожек
    # и здания ложатся поверх
    for _, _, outer, holes, _, cls in osm_layers.squares():
        for ring in outer:
            draw.polygon([px(p) for p in ring], fill=index[cls])
        for ring in holes:
            draw.polygon([px(p) for p in ring], fill=0)
    idx = np.array(img)
    shore, riprap = shore_band(r, n)
    soft = np.isin(idx, (0, index["Earth"], index["Shore"]))
    idx[shore & soft] = index["Shore"]
    idx[riprap & soft] = index["Riprap"]
    img = Image.fromarray(idx)
    draw = ImageDraw.Draw(img)
    # захаб — асфальт от стены до стены (фото build/cat_refs/n_zahab.jpg; в OSM там только дорожка 68666634 без
    # ширины), линии поверх: проезд Великих ворот (булыжник, osm_layers.WAY_OVERRIDE)
    zk = zakhab_corridor()
    draw.polygon([px(p) for p in zk[1:]], fill=index[ZAKHAB_SURFACE])
    for cls in osm_layers.PAINT:
        for line, w in lines[cls]:
            draw.line([px(p) for p in line], fill=index[cls], width=max(1, round(w * k)), joint="curve")
    # площадь у собора (osm_layers.cathedral_square) — поверх дорожек двора: территория храма без газонов и зданий
    outer, holes, rad = osm_layers.cathedral_square()
    sq = Image.new("L", (n, n), 0)
    sq_draw = ImageDraw.Draw(sq)
    sq_draw.polygon([px(p) for p in outer], fill=1)
    for ring in holes:
        sq_draw.polygon([px(p) for p in ring], fill=0)
    rows = (np.arange(n) + 0.5) / k
    near = np.hypot((HALF - rows)[:, None], (rows - HALF)[None, :]) <= rad
    idx = np.array(img)
    idx[np.asarray(sq, bool) & near] = index[osm_layers.surface_class(osm_layers.SQUARE_SURFACE, None)]
    img = Image.fromarray(idx)
    draw = ImageDraw.Draw(img)
    for ring in polys["Built"]:  # здания поверх дорожек, которые OSM проводит сквозь них
        if len(ring) > 2:
            draw.polygon([px(p) for p in ring], fill=index["Built"])
    idx = np.asarray(img)
    shares = {}
    for out, group in ((OUT_MASK, osm_layers.GROUND), (OUT_MASK2, osm_layers.GROUND2)):
        rgba = np.stack([(idx == index[c]).reshape(MAP_PX, 2, MAP_PX, 2).mean(axis=(1, 3)) for c in group], axis=-1)
        ue = np.rint(rgba[::-1, :, :].transpose(1, 0, 2) * 255).astype(np.uint8)  # как heightmap: строки — Y
        Image.fromarray(np.ascontiguousarray(ue), "RGBA").save(out)
        shares.update({c: round(float(rgba[..., i].mean()) * 100, 2) for i, c in enumerate(group)})
    return shares


