def write_heightmap(z):
    from PIL import Image
    ue = z[::-1, :].T  # [Y, X] по возрастанию: строки — восток, столбцы — север
    hm = np.clip(np.rint(32768 + ue / Z_PER_UNIT_M), 0, 65535).astype(np.uint16)
    Image.fromarray(hm).save(OUT_PNG)
    # то же 16-битное значение байтами R (старший) и G (младший) — 8-битный PNG без потерь для heights_krom.py:
    # 16-битную текстуру редактор может ужать при импорте, а RGBA8 без сжатия переносится один в один
    rg = np.zeros(hm.shape + (4,), np.uint8)
    rg[..., 0], rg[..., 1], rg[..., 3] = hm >> 8, hm & 0xFF, 255
    os.makedirs(os.path.dirname(OUT_RG), exist_ok=True)
    Image.fromarray(rg, "RGBA").save(OUT_RG)
    return hm


