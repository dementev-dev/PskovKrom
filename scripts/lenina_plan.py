"""lenina_plan.py — герои площади Ленина перед Кромом (D-043, партия 3): историко-краеведческая библиотека
им. И. И. Василева (пл. Ленина, 3; бывший кинотеатр «Октябрь») и областной «Центр семьи» (пл. Ленина, 1; бывший
Дом культуры профсоюзов). Общий источник для blockout (buildings()) и героев scripts/blender/lenina.py.

Чистый Python без `unreal` и `bpy` (нужны krom_geo и помощники pskovgu_plan, zapskovye_plan). Координаты — локальные
метры (D-013): x — север, y — восток. Оси дома, как у zapskovye_plan: u — по азимуту yaw вдоль главного фасада,
v — вправо от него (yaw + 90°), внутрь здания; z — от нуля дома (земля перед главным входом, точка base). Дом собран
из блоков zapskovye_plan.Block (четырёхугольник, карниз, кровля, фасады); особое (лопатки, ниши, фронтон, портик,
колонны) — числами ниже и функциями extras_* в scripts/blender/lenina.py. Цифры — docs/REFERENCES.md (S-156…S-161):
контуры OSM (S-02), история и описание фасадов — pleskov60 (описание кинотеатра по экспертизе, S-156), размеры
по фото Commons (build/lenina_refs/manifest.json) пропорциями по известной ширине фасада (без восстановления
камер — точность ±0,5…1 м, отмечено «гип.»).

Цвет — нынешнее состояние: кинотеатр после реконструкции 2021–2025 гг. весь белый (фото 2023 и 2025, S-157, S-158;
до неё — жёлтые стены, белые лопатки, зелёная кровля — фото 2013–2014), «Центр семьи» — белый (фото 2014, 2018).
Стены — «wall», кровли — светлая оцинковка «tin», цоколь — «stone». Новых ключей krom_plan.COLORS нет.

krom_plan импортируется лениво, внутри функций: подключение — строкой в krom_plan.buildings() (см. buildings()).

    python scripts/lenina_plan.py     # сверка планов с контурами OSM и проверка, что city_mesh снимет коробки
"""
